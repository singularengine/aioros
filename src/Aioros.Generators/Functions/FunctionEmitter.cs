using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Aioros.Generators.Pages;
using Microsoft.CodeAnalysis;

namespace Aioros.Generators.Functions;

internal sealed class FunctionEmitter(INamedTypeSymbol type, string group, IReadOnlyList<IMethodSymbol> methods, IReadOnlyList<INamedTypeSymbol> implementations, DataShapes shapes)
{
    private const string Authorize = "Microsoft.AspNetCore.Authorization.AuthorizeAttribute";
    private const string AllowAnonymous = "Microsoft.AspNetCore.Authorization.AllowAnonymousAttribute";
    private const string Runtime = "global::Aioros.Runtime.Functions.";
    private const string Data = DataCodecs.FunctionClass + ".";
    private const string Cache = "global::Aioros.Runtime.Caching.DataCache";

    private static readonly SymbolDisplayFormat Full = DataShape.Annotated;

    private readonly string _name = type.Name.Length > 1 && type.Name[0] == 'I' && char.IsUpper(type.Name[1]) ? type.Name.Substring(1) : type.Name;

    private readonly Dictionary<IMethodSymbol, FunctionKeys> _keys = methods.ToDictionary<IMethodSymbol, IMethodSymbol, FunctionKeys>(method => method, method => FunctionKeys.Of(method, implementations), SymbolEqualityComparer.Default);

    private readonly Dictionary<IMethodSymbol, FunctionMemo> _memos = methods.ToDictionary<IMethodSymbol, IMethodSymbol, FunctionMemo>(method => method, method => FunctionMemo.Of(method, Result(method), implementations), SymbolEqualityComparer.Default);

    private readonly Dictionary<IMethodSymbol, FunctionCache> _caches = methods.ToDictionary<IMethodSymbol, IMethodSymbol, FunctionCache>(method => method, method => FunctionCache.Of(method, Result(method), implementations), SymbolEqualityComparer.Default);

    public string Registration => Namespace() + _name + "Functions.Group";

    /// <summary>Every argument or result the generated code cannot write or read, with the method that sends it.</summary>
    public IEnumerable<(IMethodSymbol Method, ITypeSymbol Type, string Problem)> Problems() =>
        methods.SelectMany(method => Values(method).Select(parameter => parameter.Type).Concat(Result(method) is { } result ? [result] : [])
            .Select(data => (Method: method, Type: data, Problem: shapes.Problem(data)!))
            .Where(found => found.Problem is not null));

    /// <summary>Every <c>[Reads]</c> or <c>[Invalidates]</c> key that cannot be written from the method's arguments.</summary>
    public IEnumerable<(IMethodSymbol Method, Location? Location, string Key, string Problem)> KeyProblems() =>
        methods.SelectMany(method => _keys[method].Problems.Select(problem => (method, problem.Location, problem.Key, problem.Problem)));

    /// <summary>Every <c>[Memo]</c> whose result a loader it is shared with could change.</summary>
    public IEnumerable<(IMethodSymbol Method, Location? Location, string Problem)> MemoProblems() =>
        methods.Where(method => _memos[method].Problem is not null).Select(method => (method, _memos[method].Location, _memos[method].Problem!));

    /// <summary>Every <c>[Cached]</c> function, with what its implementation declares.</summary>
    public IEnumerable<(IMethodSymbol Method, FunctionCache Cache)> Caches() =>
        methods.Where(method => _caches[method].Marked).Select(method => (method, _caches[method]));

    /// <summary>The data shapes the group's generated code writes and reads.</summary>
    public IEnumerable<DataShape> Roots() =>
        methods.SelectMany(method => Values(method).Select(parameter => shapes.Of(parameter.Type)).Concat(Result(method) is { } result ? [shapes.Of(result)] : []));

    public string Source()
    {
        var interfaceName = type.ToDisplayString(Full);
        var access = type.DeclaredAccessibility == Accessibility.Public ? "public" : "internal";
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        if (!type.ContainingNamespace.IsGlobalNamespace)
        {
            code.Append("namespace ").Append(type.ContainingNamespace.ToDisplayString()).Append(";\n\n");
        }

        code.Append("/// <summary>Calls the server functions of <see cref=\"").Append(type.Name).Append("\"/> over HTTP.</summary>\n");
        code.Append(access).Append(" sealed class ").Append(_name).Append("Client(global::System.Net.Http.HttpClient http) : ").Append(interfaceName).Append("\n{\n");
        code.Append("    internal const string Contract = \"").Append(Contract()).Append("\";\n");
        foreach (var method in methods)
        {
            ClientMethod(code, method);
        }

        foreach (var method in methods)
        {
            code.Append("\n    private readonly record struct ").Append(method.Name).Append("Arguments(")
                .Append(string.Join(", ", Values(method).Select(parameter => parameter.Type.ToDisplayString(Full) + " " + Pascal(parameter.Name))))
                .Append(");\n");
        }

        code.Append("}\n\n");
        InProcess(code, access, interfaceName);
        code.Append("/// <summary>The server functions of <see cref=\"").Append(type.Name).Append("\"/> for the dispatcher and the registry.</summary>\n");
        code.Append(access).Append(" static class ").Append(_name).Append("Functions\n{\n");
        code.Append("    public static ").Append(Runtime).Append("ServerFunctionGroup Group { get; } = new(\n");
        code.Append("        typeof(").Append(type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)).Append("),\n        \"").Append(group).Append("\",\n        ").Append(_name).Append("Client.Contract,\n        [\n");
        foreach (var method in methods)
        {
            Route(code, method, interfaceName);
        }

        code.Append("        ],\n        static http => new ").Append(_name).Append("Client(http))\n    {\n");
        code.Append("        InProcess = static implementation => new ").Append(_name).Append("InProcess((").Append(interfaceName).Append(")implementation),\n    };\n}\n");
        return code.ToString();
    }

    private void ClientMethod(StringBuilder code, IMethodSymbol method)
    {
        var token = Token(method);
        var parameters = string.Join(", ", method.Parameters.Select(parameter => parameter.Type.ToDisplayString(Full) + " " + Escape(parameter.Name)));
        var result = Result(method);
        code.Append("\n    public ").Append(method.ReturnType.ToDisplayString(Full)).Append(' ').Append(method.Name).Append('(').Append(parameters).Append(") =>\n");
        code.Append("        ").Append(Runtime).Append("ServerFunctionCalls.CallAsync<").Append(method.Name).Append("Arguments")
            .Append(result is null ? string.Empty : ", " + result.ToDisplayString(Full)).Append(">(\n");
        code.Append("            http,\n            \"").Append(group).Append("\",\n            \"").Append(RouteName(method)).Append("\",\n            Contract,\n            new ").Append(method.Name).Append("Arguments(")
            .Append(string.Join(", ", Values(method).Select(parameter => Escape(parameter.Name))))
            .Append("),\n            static (w, a) =>\n            {\n                w.WriteStartObject();\n");
        foreach (var parameter in Values(method))
        {
            code.Append("                w.WritePropertyName(\"").Append(Camel(parameter.Name)).Append("\");\n                ")
                .Append(DataCodecs.Write(shapes.Of(parameter.Type), "a." + Pascal(parameter.Name), Data)).Append('\n');
        }

        code.Append("                w.WriteEndObject();\n            },\n");
        if (result is not null)
        {
            code.Append("            static e => ").Append(DataCodecs.Read(shapes.Of(result), "e", Data)).Append(",\n");
        }

        code.Append("            ").Append(_keys[method].Declared ? "true" : "false").Append(",\n");
        code.Append("            ").Append(token is null ? "global::System.Threading.CancellationToken.None" : Escape(token.Name)).Append(");\n");
    }

    private void InProcess(StringBuilder code, string access, string interfaceName)
    {
        code.Append("/// <summary>Calls the server implementation of <see cref=\"").Append(type.Name).Append("\"/> in process, failing as its client would.</summary>\n");
        code.Append(access).Append(" sealed class ").Append(_name).Append("InProcess(").Append(interfaceName).Append(" implementation__) : ").Append(interfaceName)
            .Append(", ").Append(Runtime).Append("IKeyedCalls, ").Append(Runtime).Append("ICachedCalls\n{\n");
        code.Append("    private global::Aioros.Functions.IDataKeys? keys__;\n\n");
        code.Append("    private ").Append(Cache).Append("? cache__;\n\n");
        code.Append("    global::Aioros.Functions.IDataKeys? ").Append(Runtime).Append("IKeyedCalls.Keys { get => keys__; set => keys__ = value; }\n\n");
        code.Append("    ").Append(Cache).Append("? ").Append(Runtime).Append("ICachedCalls.Cache { get => cache__; set => cache__ = value; }\n\n");
        foreach (var method in methods)
        {
            var parameters = string.Join(", ", method.Parameters.Select(parameter => parameter.Type.ToDisplayString(Full) + " " + Escape(parameter.Name)));
            var direct = "implementation__." + method.Name + "(" + string.Join(", ", method.Parameters.Select(parameter => Escape(parameter.Name))) + ")";
            var result = Result(method) is not null;
            var memo = result && _memos[method].Marked;
            var inner = memo
                ? "(keys__ is " + Runtime + "ICallMemo memo__ ? Memo" + method.Name + "(memo__" + string.Concat(method.Parameters.Select(parameter => ", " + Escape(parameter.Name))) + ") : " + direct + ")"
                : direct;
            var cached = result && _caches[method].Caches;
            var call = (cached
                ? "(cache__ is { } cached__ ? Cached" + method.Name + "(cached__" + string.Concat(method.Parameters.Select(parameter => ", " + Escape(parameter.Name))) + ") : " + inner + ")"
                : inner) + ".ConfigureAwait(false)";
            code.Append("    public async ").Append(method.ReturnType.ToDisplayString(Full)).Append(' ').Append(method.Name).Append('(').Append(parameters).Append(")\n    {\n");
            code.Append("        try\n        {\n            ").Append(result ? "var result__ = await " : "await ").Append(call).Append(";\n");
            _keys[method].Record(code, "            ");
            code.Append(result ? "            return result__;\n" : string.Empty).Append("        }\n");
            code.Append("        catch (global::System.Exception failure__) when (!").Append(Runtime).Append("ServerFunctionFailures.Passes(failure__))\n        {\n");
            code.Append("            throw ").Append(Runtime).Append("ServerFunctionFailures.Failed(failure__);\n        }\n    }\n\n");
            if (memo)
            {
                Memo(code, method, direct);
            }

            if (cached)
            {
                Cached(code, method, inner);
            }
        }

        code.Length -= 1;
        code.Append("}\n\n");
    }

    /// <summary>
    /// The call of a <c>[Memo]</c> function through the load's memo, in a method of its own so that only a memoized call
    /// captures its arguments: keyed by the group, the function and its arguments as a tuple, compared by value.
    /// </summary>
    private void Memo(StringBuilder code, IMethodSymbol method, string direct)
    {
        var parameters = string.Concat(method.Parameters.Select(parameter => ", " + parameter.Type.ToDisplayString(Full) + " " + Escape(parameter.Name)));
        code.Append("    private ").Append(method.ReturnType.ToDisplayString(Full)).Append(" Memo").Append(method.Name).Append('(').Append(Runtime).Append("ICallMemo memo__").Append(parameters).Append(") =>\n");
        code.Append("        memo__.CallAsync<").Append(Result(method)!.ToDisplayString(Full)).Append(">(\"").Append(group).Append('/').Append(RouteName(method)).Append("\", ")
            .Append(Arguments(method)).Append(", () => ").Append(direct).Append(");\n\n");
    }

    /// <summary>
    /// The call of a <c>[Cached]</c> function through the app's data cache, in a method of its own so that only a cached
    /// call captures its arguments: keyed by the group, the function and its arguments, with its lifetime, whether it is
    /// shared and its read keys written from the arguments; the load's services (<c>keys__</c>) tell a load from a command
    /// and carry the user.
    /// </summary>
    private void Cached(StringBuilder code, IMethodSymbol method, string inner)
    {
        var cache = _caches[method];
        var parameters = string.Concat(method.Parameters.Select(parameter => ", " + parameter.Type.ToDisplayString(Full) + " " + Escape(parameter.Name)));
        code.Append("    private ").Append(method.ReturnType.ToDisplayString(Full)).Append(" Cached").Append(method.Name).Append('(').Append(Cache).Append(" cached__").Append(parameters).Append(") =>\n");
        code.Append("        cached__.CallAsync<").Append(Result(method)!.ToDisplayString(Full)).Append(">(\"").Append(group).Append('/').Append(RouteName(method)).Append("\", ")
            .Append(Arguments(method)).Append(", keys__, global::System.TimeSpan.FromSeconds(").Append(cache.Seconds.ToString(CultureInfo.InvariantCulture)).Append("), ")
            .Append(cache.Shared ? "true" : "false").Append(", [").Append(string.Join(", ", _keys[method].Reads)).Append("], () => ").Append(inner).Append(");\n\n");
    }

    private static string Arguments(IMethodSymbol method)
    {
        var values = Values(method).Select(parameter => Escape(parameter.Name)).ToList();
        return values.Count switch
        {
            0 => "default(global::System.ValueTuple)",
            1 => "global::System.ValueTuple.Create(" + values[0] + ")",
            _ => "(" + string.Join(", ", values) + ")",
        };
    }

    private void Route(StringBuilder code, IMethodSymbol method, string interfaceName)
    {
        var index = 0;
        var arguments = new List<string>();
        code.Append("            new ").Append(Runtime).Append("ServerFunctionRoute(\"").Append(RouteName(method)).Append("\", static async (service, arguments, cancellationToken) =>\n            {\n");
        foreach (var parameter in method.Parameters)
        {
            if (IsToken(parameter.Type))
            {
                arguments.Add("cancellationToken");
                continue;
            }

            var name = index.ToString(CultureInfo.InvariantCulture);
            code.Append("                var a").Append(name).Append(" = ").Append(Runtime).Append("ServerFunctionArguments.TryGet(arguments, \"").Append(Camel(parameter.Name)).Append("\", out var e").Append(name)
                .Append(") ? ").Append(DataCodecs.Read(shapes.Of(parameter.Type), "e" + name, Data)).Append(" : default!;\n");
            arguments.Add("a" + name);
            index++;
        }

        var call = "((" + interfaceName + ")service)." + method.Name + "(" + string.Join(", ", arguments) + ")";
        var result = Result(method);
        code.Append(result is null ? "                await " + call + ";\n                return null;\n" : "                return await " + call + ";\n");
        code.Append("            })");
        var initializers = new List<string>();
        var rules = Access(method).ToList();
        if (rules.Count > 0)
        {
            initializers.Add("Access = [" + string.Join(", ", rules.Select(rule =>
                "new " + Runtime + "ServerFunctionAccess(" + Optional(Named(rule, "Policy", constructor: true)) + ", " + Optional(Named(rule, "Roles", constructor: false)) + ")")) + "]");
        }

        if (result is not null)
        {
            initializers.Add("Write = static (w, value) => { " + DataCodecs.Write(shapes.Of(result), "((" + result.ToDisplayString(Full) + ")value!)", Data) + " }");
        }

        if (_keys[method].Declared)
        {
            initializers.Add("Keyed = true");
        }

        if (initializers.Count > 0)
        {
            code.Append(" { ").Append(string.Join(", ", initializers)).Append(" }");
        }

        code.Append(",\n");
    }

    private IEnumerable<AttributeData> Access(IMethodSymbol method)
    {
        var interfaceRules = type.GetAttributes().Concat(method.GetAttributes());
        var implementationRules = implementations.SelectMany(implementation =>
            implementation.FindImplementationForInterfaceMember(method) is IMethodSymbol member
                ? implementation.GetAttributes().Concat(member.GetAttributes())
                : implementation.GetAttributes());
        var rules = interfaceRules.Concat(implementationRules).ToList();
        return rules.Any(rule => rule.AttributeClass?.ToDisplayString() == AllowAnonymous)
            ? []
            : rules.Where(rule => rule.AttributeClass?.ToDisplayString() == Authorize);
    }

    private static string? Named(AttributeData attribute, string name, bool constructor) =>
        (constructor ? attribute.ConstructorArguments.FirstOrDefault().Value as string : null)
        ?? attribute.NamedArguments.FirstOrDefault(argument => argument.Key == name).Value.Value as string;

    private static string Optional(string? text) => text is null ? "null" : "@\"" + text.Replace("\"", "\"\"") + "\"";

    private string Contract()
    {
        var shape = new StringBuilder(group);
        foreach (var method in methods)
        {
            shape.Append('|').Append(RouteName(method)).Append('(')
                .Append(string.Join(",", Values(method).Select(parameter => parameter.Type.ToDisplayString(Full) + " " + parameter.Name)))
                .Append(")->").Append(method.ReturnType.ToDisplayString(Full));
        }

        shape.Append("|data:");
        foreach (var method in methods)
        {
            shape.Append('|').Append(string.Join(",", Values(method).Select(parameter => shapes.Describe(parameter.Type))))
                .Append("->").Append(Result(method) is { } result ? shapes.Describe(result) : "void");
        }

        return DataCodecs.Hash(shape.ToString());
    }

    private static string RouteName(IMethodSymbol method)
    {
        var named = method.GetAttributes().FirstOrDefault(data => data.AttributeClass?.ToDisplayString() == "Aioros.Functions.ServerFunctionAttribute");
        if (named?.ConstructorArguments.FirstOrDefault().Value is string name)
        {
            return name;
        }

        var bare = method.Name.EndsWith("Async", System.StringComparison.Ordinal) && method.Name.Length > 5 ? method.Name.Substring(0, method.Name.Length - 5) : method.Name;
        return Camel(bare);
    }

    private static ITypeSymbol? Result(IMethodSymbol method) =>
        method.ReturnType is INamedTypeSymbol { TypeArguments.Length: 1 } task ? task.TypeArguments[0] : null;

    private static IEnumerable<IParameterSymbol> Values(IMethodSymbol method) => method.Parameters.Where(parameter => !IsToken(parameter.Type));

    private static IParameterSymbol? Token(IMethodSymbol method) => method.Parameters.FirstOrDefault(parameter => IsToken(parameter.Type));

    private static bool IsToken(ITypeSymbol type) => type.ToDisplayString() == "System.Threading.CancellationToken";

    private string Namespace() => type.ContainingNamespace.IsGlobalNamespace ? "global::" : "global::" + type.ContainingNamespace.ToDisplayString() + ".";

    private static string Camel(string name) => name.Length == 0 ? name : char.ToLowerInvariant(name[0]) + name.Substring(1);

    private static string Pascal(string name) => name.Length == 0 ? name : char.ToUpperInvariant(name[0]) + name.Substring(1);

    private static string Escape(string name) => Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name) == Microsoft.CodeAnalysis.CSharp.SyntaxKind.None ? name : "@" + name;
}
