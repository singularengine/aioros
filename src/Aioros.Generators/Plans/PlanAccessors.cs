using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Aioros.Generators.Plans;

/// <summary>
/// Typed getters and setters for the members plans read: every public instance property and field of the types the XAML
/// names in <c>x:DataType</c> and of the types reached from them, emitted as code instead of delegates compiled at run
/// time (EF Core's compiled model; the configuration binding generator walks the graph from each <c>Bind&lt;T&gt;</c>).
/// A type from a referenced framework is not walked, but gets its members when a binding path of the XAML reaches it.
/// </summary>
internal static class PlanAccessors
{
    public const string AccessorType = "Aioros.Runtime.Rendering.MemberAccessor";

    private static readonly SymbolDisplayFormat Full = SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(
        SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions | SymbolDisplayMiscellaneousOptions.ExpandValueTuple);

    private static readonly HashSet<string> DataNamespaces = new(StringComparer.Ordinal)
    {
        "System", "System.Collections.Generic", "System.Collections.ObjectModel", "System.Collections.Immutable", "Avalonia",
    };

    private static readonly HashSet<string> SkippedAttributes = new(StringComparer.Ordinal)
    {
        "System.ObsoleteAttribute", "System.Diagnostics.CodeAnalysis.ExperimentalAttribute",
        "System.Diagnostics.CodeAnalysis.RequiresUnreferencedCodeAttribute", "System.Diagnostics.CodeAnalysis.RequiresDynamicCodeAttribute",
        "System.Runtime.Versioning.SupportedOSPlatformAttribute", "System.Runtime.Versioning.UnsupportedOSPlatformAttribute",
    };

    public const string DeferredType = "Aioros.Runtime.Rendering.DeferredAccessors";

    public static string Emit(Compilation compilation, IEnumerable<string> dataTypes, IEnumerable<string> paths)
    {
        var roots = dataTypes.Distinct(StringComparer.Ordinal).Select(compilation.GetTypeByMetadataName).OfType<ITypeSymbol>();
        var split = paths.Distinct(StringComparer.Ordinal).Select(path => path.Split('.')).ToList();
        var owners = Owners(compilation, roots, paths);
        var members = new Dictionary<ITypeSymbol, Dictionary<string, ITypeSymbol?>>(SymbolEqualityComparer.Default);
        var deferred = compilation.GetTypeByMetadataName(DeferredType) is not null;
        var code = new StringBuilder("""
            // <auto-generated/>
            #nullable disable

            namespace Aioros.Generated
            {
                internal static class AiorosAccessors
                {
                    public static global::System.Collections.Immutable.ImmutableArray<global::Aioros.Runtime.Rendering.MemberAccessor> All
                    {

            """);
        foreach (var validated in owners.Where(owner => owner is INamedTypeSymbol && !Framework(owner) && owner.AllInterfaces.Any(face => face.ToDisplayString() == "System.ComponentModel.INotifyDataErrorInfo")))
        {
            code.Append("            [global::System.Diagnostics.CodeAnalysis.DynamicDependency(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes.PublicProperties, typeof(")
                .Append(validated.ToDisplayString(Full)).Append("))]\n");
        }

        code.Append("            get;\n        } =\n        [\n");
        var indexes = Indexes(split);
        foreach (var owner in owners.Where(owner => !(deferred && Deferred(owner))))
        {
            Accessors(code, compilation, owner, "            ");
            MethodCommands(code, owner, split, members, "            ");
            Elements(code, owner, indexes, "            ");
        }

        code.Append("        ];\n");
        if (deferred)
        {
            code.Append("\n        public static global::System.Collections.Immutable.ImmutableArray<global::Aioros.Runtime.Rendering.DeferredAccessors> Deferred { get; } =\n        [\n");
            foreach (var owner in owners.Where(Deferred))
            {
                code.Append("            new(\"").Append(Plans.PlanCode.MetadataName((INamedTypeSymbol)owner)).Append("\", static () =>\n            [\n");
                Accessors(code, compilation, owner, "                ");
                MethodCommands(code, owner, split, members, "                ");
                code.Append("            ]),\n");
            }

            code.Append("        ];\n");
        }

        return code.Append("""
                }
            }

            """).ToString();
    }

    /// <summary>
    /// An Avalonia type reached from the XAML (a <c>Point</c> in a list a polyline draws): its accessors are created only when
    /// a value of it is read, so listing them does not load Avalonia in an app that never reads one.
    /// </summary>
    private static bool Deferred(ITypeSymbol type) =>
        type is INamedTypeSymbol { IsGenericType: false } && Root(type) == "Avalonia" && Framework(type);

    private static string? Root(ITypeSymbol type)
    {
        var root = type.ContainingNamespace;
        while (root?.ContainingNamespace is { IsGlobalNamespace: false })
        {
            root = root.ContainingNamespace;
        }

        return root?.Name;
    }

    private static void Accessors(StringBuilder code, Compilation compilation, ITypeSymbol owner, string indent)
    {
        var name = owner.ToDisplayString(Full);
        foreach (var member in Members(compilation, owner))
        {
            code.Append(indent).Append("new(typeof(").Append(name).Append("), \"").Append(member.Name).Append("\", static target => ((")
                .Append(name).Append(")target).").Append(member.Name).Append(')');
            if (member.Setter is { } type)
            {
                code.Append(" { ValueType = static () => typeof(").Append(type).Append("), Set = static (target, value) => ((").Append(name).Append(")target).")
                    .Append(member.Name).Append(" = (").Append(type).Append(")value }");
            }

            code.Append(",\n");
        }
    }

    /// <summary>
    /// A path segment's member and its integer indexes (<c>Items[1][0]</c> is <c>Items</c>, 1 and 0), or the segment
    /// itself with no index when its brackets do not hold integers.
    /// </summary>
    internal static string Indexed(string segment, out List<int> indexes)
    {
        indexes = [];
        var bracket = segment.IndexOf('[');
        if (bracket < 0)
        {
            return segment;
        }

        var rest = segment.Substring(bracket);
        while (rest.Length > 0)
        {
            var close = rest.IndexOf(']');
            if (rest[0] != '[' || close < 2 || !int.TryParse(rest.Substring(1, close - 1), System.Globalization.NumberStyles.None, System.Globalization.CultureInfo.InvariantCulture, out var index))
            {
                indexes.Clear();
                return segment;
            }

            indexes.Add(index);
            rest = rest.Substring(close + 1);
        }

        return segment.Substring(0, bracket);
    }

    /// <summary>Every integer index the binding paths read.</summary>
    private static List<int> Indexes(List<string[]> paths) =>
        [.. paths.SelectMany(path => path).SelectMany(segment => { Indexed(segment, out var found); return found; }).Distinct().OrderBy(index => index)];

    /// <summary>
    /// The elements at the indexes the paths read of a type that is a read-only list and not an <c>IList</c> (which member
    /// paths read directly): <c>[n]</c> reads its element, or null out of range, as Avalonia's binding then gives no value.
    /// </summary>
    private static void Elements(StringBuilder code, ITypeSymbol owner, List<int> indexes, string indent)
    {
        if (indexes.Count == 0 || owner.AllInterfaces.Any(face => face.ToDisplayString() == "System.Collections.IList")
            || owner.AllInterfaces.FirstOrDefault(face => face.OriginalDefinition.ToDisplayString() == "System.Collections.Generic.IReadOnlyList<T>") is not { } list)
        {
            return;
        }

        var name = owner.ToDisplayString(Full);
        var face = list.ToDisplayString(Full);
        foreach (var index in indexes)
        {
            var at = index.ToString(System.Globalization.CultureInfo.InvariantCulture);
            code.Append(indent).Append("new(typeof(").Append(name).Append("), \"[").Append(at).Append("]\", static target => (").Append(face).Append(")target is { Count: > ")
                .Append(at).Append(" } list ? (object)list[").Append(at).Append("] : null),\n");
        }
    }

    /// <summary>
    /// The methods binding paths name as their last member on this type, run as commands as Avalonia runs a <c>Command</c>
    /// bound to a method (its <c>MethodToCommandConverter</c>): the member <c>Method()</c> reads a
    /// <c>MethodCommand</c> that calls the method, awaited when it returns a task, with the parameter converted to its type,
    /// and asks <c>Can&lt;Method&gt;(object)</c> when there is one.
    /// </summary>
    private static void MethodCommands(StringBuilder code, ITypeSymbol owner, List<string[]> paths, Dictionary<ITypeSymbol, Dictionary<string, ITypeSymbol?>> members, string indent)
    {
        var name = owner.ToDisplayString(Full);
        foreach (var method in paths.Select(path => Commanded(owner, path, members)).OfType<IMethodSymbol>().Distinct<IMethodSymbol>(SymbolEqualityComparer.Default).OrderBy(method => method.Name, StringComparer.Ordinal))
        {
            var argument = method.Parameters.Length == 0 ? string.Empty : "global::Aioros.Runtime.Slots.MethodCommand.Argument<" + method.Parameters[0].Type.ToDisplayString(Full) + ">(parameter)";
            var call = "((" + name + ")target)." + method.Name + "(" + argument + ")";
            var run = method.ReturnsVoid ? "{ " + call + "; return default; }" : Plans.PlanCode.Awaited(method.ReturnType, call) ?? "{ _ = " + call + "; return default; }";
            var guard = Hierarchy(owner).SelectMany(type => type.GetMembers("Can" + method.Name)).OfType<IMethodSymbol>()
                .Any(can => can is { IsStatic: false, DeclaredAccessibility: Accessibility.Public, MethodKind: MethodKind.Ordinary, ReturnType.SpecialType: SpecialType.System_Boolean, Parameters.Length: 1 }
                    && can.Parameters[0].Type.SpecialType == SpecialType.System_Object)
                ? "parameter => ((" + name + ")target).Can" + method.Name + "(parameter)"
                : "null";
            code.Append(indent).Append("new(typeof(").Append(name).Append("), \"").Append(method.Name).Append("()\", static target => new global::Aioros.Runtime.Slots.MethodCommand(parameter => ")
                .Append(run).Append(", ").Append(guard).Append(")),\n");
        }
    }

    /// <summary>
    /// The method a path names as its last member, when this type has it as a single public instance method with at most
    /// one plain parameter and no property or field of that name: a path is relative to the scope it is read on, so its
    /// last member is looked up on every type that may hold it.
    /// </summary>
    private static IMethodSymbol? Commanded(ITypeSymbol owner, string[] path, Dictionary<ITypeSymbol, Dictionary<string, ITypeSymbol?>> members)
    {
        var last = path[path.Length - 1];
        if (Named(owner, members).ContainsKey(last))
        {
            return null;
        }

        var methods = Hierarchy(owner).SelectMany(type => type.GetMembers(last)).OfType<IMethodSymbol>()
            .Where(method => method is { IsStatic: false, IsGenericMethod: false, DeclaredAccessibility: Accessibility.Public, MethodKind: MethodKind.Ordinary })
            .ToList();
        methods.RemoveAll(method => methods.Any(other => SymbolEqualityComparer.Default.Equals(other.OverriddenMethod, method)));
        return methods.Count == 1 && methods[0].Parameters.Length <= 1 && methods[0].Parameters.All(parameter => parameter.RefKind == RefKind.None && !parameter.IsParams)
            ? methods[0]
            : null;
    }

    internal static List<ITypeSymbol> Owners(Compilation compilation, IEnumerable<ITypeSymbol> roots, IEnumerable<string>? paths = null)
    {
        var start = roots.ToList();
        var (owners, walked) = Walk(compilation, start);
        var listed = new HashSet<ITypeSymbol>(owners, SymbolEqualityComparer.Default);
        var members = new Dictionary<ITypeSymbol, Dictionary<string, ITypeSymbol?>>(SymbolEqualityComparer.Default);
        var split = (paths ?? []).Distinct(StringComparer.Ordinal).Select(path => path.Split('.')).ToList();
        owners.AddRange(start.Where(Framework).Concat(walked.SelectMany(type => ThroughPaths(type, split, members)))
            .Distinct<ITypeSymbol>(SymbolEqualityComparer.Default)
            .Where(type => !listed.Contains(type) && Framework(type) && Owner(type) && !Unreached(compilation, type))
            .ToList());
        return [.. owners.OrderBy(owner => owner.ToDisplayString(Full), StringComparer.Ordinal)];
    }

    /// <summary>The types the graph walk emits, and the app's types it walked through.</summary>
    private static (List<ITypeSymbol> Owners, List<ITypeSymbol> Walked) Walk(Compilation compilation, List<ITypeSymbol> roots)
    {
        var seen = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
        var owners = new List<ITypeSymbol>();
        var walked = new List<ITypeSymbol>();
        var pending = new Queue<ITypeSymbol>(roots);
        var implementations = new Lazy<List<INamedTypeSymbol>>(() => [.. Pages.PageLoaders.Types(compilation.Assembly.GlobalNamespace)
            .Where(type => type.TypeKind is TypeKind.Class or TypeKind.Struct && !type.IsAbstract && !type.IsStatic)]);
        while (pending.Count > 0)
        {
            var type = pending.Dequeue();
            if (!seen.Add(type) || Unreached(compilation, type))
            {
                continue;
            }

            var data = type is IArrayTypeSymbol || Framework(type);
            if (Emitted(type, data))
            {
                owners.Add(type);
            }

            if (!data)
            {
                walked.Add(type);
            }

            foreach (var next in Reached(type, data).Concat(Implementations(type, implementations)))
            {
                pending.Enqueue(next);
            }
        }

        return (owners, walked);
    }

    /// <summary>The framework types a binding path reaches from a type: each member it names, read on the type the one before holds.</summary>
    private static IEnumerable<ITypeSymbol> ThroughPaths(ITypeSymbol type, List<string[]> paths, Dictionary<ITypeSymbol, Dictionary<string, ITypeSymbol?>> members)
    {
        foreach (var path in paths)
        {
            var current = type;
            var found = new List<ITypeSymbol>();
            foreach (var segment in path)
            {
                current = Step(current, segment, members, found);
                if (current is null)
                {
                    break;
                }
            }

            foreach (var reached in found)
            {
                yield return reached;
            }
        }
    }

    /// <summary>
    /// The type a path segment reads from a type (a member, then the element of each index it reads), noting the framework
    /// types it passes through, or nothing where the path leaves the members the generator knows.
    /// </summary>
    private static ITypeSymbol? Step(ITypeSymbol current, string segment, Dictionary<ITypeSymbol, Dictionary<string, ITypeSymbol?>> members, List<ITypeSymbol> found)
    {
        var member = Indexed(segment, out var indexes);
        if (!Named(current, members).TryGetValue(member, out var next))
        {
            return null;
        }

        for (var index = 0; next is not null && index <= indexes.Count; index++)
        {
            if (Framework(next))
            {
                found.Add(next);
            }

            next = index < indexes.Count ? Element(next) : next;
        }

        return next;
    }

    /// <summary>The element type of an array or a list, or nothing.</summary>
    private static ITypeSymbol? Element(ITypeSymbol type) =>
        type is IArrayTypeSymbol array ? array.ElementType
        : (type is INamedTypeSymbol { IsGenericType: true } named && named.OriginalDefinition.ToDisplayString() is "System.Collections.Generic.IReadOnlyList<T>" or "System.Collections.Generic.IList<T>" ? named : null)?.TypeArguments[0]
            ?? type.AllInterfaces.FirstOrDefault(face => face.OriginalDefinition.ToDisplayString() is "System.Collections.Generic.IReadOnlyList<T>" or "System.Collections.Generic.IList<T>")?.TypeArguments[0];

    private static Dictionary<string, ITypeSymbol?> Named(ITypeSymbol type, Dictionary<ITypeSymbol, Dictionary<string, ITypeSymbol?>> members)
    {
        if (!members.TryGetValue(type, out var found))
        {
            found = new Dictionary<string, ITypeSymbol?>(StringComparer.Ordinal);
            foreach (var candidate in Candidates([.. Hierarchy(type).SelectMany(owner => owner.GetMembers())]).Where(candidate => !found.ContainsKey(candidate.Name)))
            {
                found[candidate.Name] = candidate.Type;
            }

            members[type] = found;
        }

        return found;
    }

    private static bool Emitted(ITypeSymbol type, bool data) =>
        Owner(type) && (!data || type is IArrayTypeSymbol || DataNamespaces.Contains(type.ContainingNamespace?.ToDisplayString() ?? string.Empty));

    private static IEnumerable<ITypeSymbol> Implementations(ITypeSymbol type, Lazy<List<INamedTypeSymbol>> implementations) =>
        type.TypeKind == TypeKind.Interface || type.IsAbstract
            ? implementations.Value.Where(candidate => Derives(candidate, type))
            : [];

    private static IEnumerable<ITypeSymbol> Reached(ITypeSymbol type, bool data)
    {
        if (type is IArrayTypeSymbol array)
        {
            yield return array.ElementType;
            yield break;
        }

        if (type is INamedTypeSymbol named)
        {
            foreach (var argument in named.TypeArguments)
            {
                yield return argument;
            }
        }

        foreach (var face in type.AllInterfaces.Where(face => face.IsGenericType && face.ConstructedFrom.SpecialType == SpecialType.System_Collections_Generic_IEnumerable_T))
        {
            yield return face.TypeArguments[0];
        }

        if (data)
        {
            yield break;
        }

        foreach (var candidate in Candidates(Hierarchy(type).SelectMany(owner => owner.GetMembers()).ToList()))
        {
            if (candidate.Type is { } reached)
            {
                yield return reached;
            }
        }
    }

    private static bool Unreached(Compilation compilation, ITypeSymbol type) =>
        type.TypeKind is TypeKind.TypeParameter or TypeKind.Pointer or TypeKind.FunctionPointer or TypeKind.Dynamic or TypeKind.Error or TypeKind.Delegate
        || type.IsRefLikeType || type.IsAnonymousType
        || (type is INamedTypeSymbol { IsUnboundGenericType: true })
        || Contains(type)
        || !compilation.IsSymbolAccessibleWithin(type, compilation.Assembly)
        || Skipped(type);

    private static bool Contains(ITypeSymbol type) => type switch
    {
        ITypeParameterSymbol => true,
        IArrayTypeSymbol array => Contains(array.ElementType),
        INamedTypeSymbol named => named.TypeArguments.Any(Contains) || (named.ContainingType is { } outer && Contains(outer)),
        _ => false,
    };

    private static bool Owner(ITypeSymbol type) => type switch
    {
        IArrayTypeSymbol => true,
        INamedTypeSymbol named => named.TypeKind is TypeKind.Class or TypeKind.Struct && !named.IsAbstract && !named.IsStatic && !named.IsTupleType
            && named.OriginalDefinition.SpecialType != SpecialType.System_Nullable_T,
        _ => false,
    };

    /// <summary>
    /// A type from a referenced framework: declared outside the app's sources in a framework's namespace. The app's own
    /// types are never one, whatever their namespace (ReactiveUI's samples live in <c>ReactiveUI.Samples</c>).
    /// </summary>
    internal static bool Framework(ITypeSymbol type) =>
        Root(type) is "System" or "Microsoft" or "Avalonia" or "CommunityToolkit" or "ReactiveUI" or "Windows" or "Internal"
        && !type.Locations.Any(location => location.IsInSource);

    private static bool Derives(INamedTypeSymbol candidate, ITypeSymbol type) =>
        candidate.AllInterfaces.Contains(type, SymbolEqualityComparer.Default)
        || Hierarchy(candidate).Skip(1).Contains(type, SymbolEqualityComparer.Default);

    internal static IEnumerable<ITypeSymbol> Hierarchy(ITypeSymbol type)
    {
        if (type is IArrayTypeSymbol array)
        {
            type = array.BaseType!;
        }

        for (var current = type; current is not null && current.SpecialType != SpecialType.System_Object; current = current.BaseType)
        {
            yield return current;
        }
    }

    private static bool Readable(ISymbol member) => member switch
    {
        IPropertySymbol property => !property.IsStatic && !property.IsIndexer && property.DeclaredAccessibility == Accessibility.Public
            && property.GetMethod is { DeclaredAccessibility: Accessibility.Public } && property.RefKind == RefKind.None
            && !property.Type.IsRefLikeType && property.Type.TypeKind is not (TypeKind.Pointer or TypeKind.FunctionPointer) && !Skipped(property),
        IFieldSymbol field => !field.IsStatic && !field.IsConst && field.DeclaredAccessibility == Accessibility.Public && field.RefKind == RefKind.None
            && !field.Type.IsRefLikeType && field.Type.TypeKind is not (TypeKind.Pointer or TypeKind.FunctionPointer) && !Skipped(field),
        _ => false,
    };

    private static bool Skipped(ISymbol symbol) =>
        symbol.GetAttributes().Any(attribute => attribute.AttributeClass is { } type && SkippedAttributes.Contains(type.ToDisplayString()))
        || (symbol.ContainingType is { } outer && Skipped(outer));

    private static IEnumerable<(string Name, string? Setter)> Members(Compilation compilation, ITypeSymbol owner)
    {
        var all = Hierarchy(owner).SelectMany(type => type.GetMembers()).ToList();
        var overridden = new HashSet<ISymbol>(all.OfType<IPropertySymbol>().Select(property => property.OverriddenProperty).OfType<ISymbol>(), SymbolEqualityComparer.Default);
        var names = all.Where(member => member.DeclaredAccessibility == Accessibility.Public && !overridden.Contains(member) && member is not IMethodSymbol { MethodKind: not MethodKind.Ordinary })
            .Select(member => member.Name)
            .Concat(Candidates(all).Where(candidate => candidate.Generated).Select(candidate => candidate.Name))
            .GroupBy(name => name, StringComparer.Ordinal)
            .Where(group => group.Count() == 1)
            .Select(group => group.Key);
        var unique = new HashSet<string>(names, StringComparer.Ordinal);
        foreach (var candidate in Candidates(all).Where(candidate => unique.Contains(candidate.Name) && SyntaxFacts(candidate.Name)).OrderBy(candidate => candidate.Name, StringComparer.Ordinal))
        {
            var setter = candidate.Settable && owner.TypeKind == TypeKind.Class && candidate.Type is { } type && Typeable(compilation, type)
                ? type.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString(Full)
                : null;
            yield return (candidate.Name, setter);
        }
    }

    /// <summary>
    /// The members a typed accessor can read: public instance properties and fields, and the properties CommunityToolkit.Mvvm
    /// generates (from an <c>[ObservableProperty]</c> field and a <c>[RelayCommand]</c> method) and ReactiveUI.SourceGenerators
    /// generates (from a <c>[Reactive]</c> field and a <c>[ReactiveCommand]</c> method), named by their rules, since one
    /// generator cannot see another's output; found by their attribute names, without referencing the toolkits.
    /// </summary>
    internal static IEnumerable<Candidate> Candidates(IReadOnlyList<ISymbol> members)
    {
        foreach (var member in members)
        {
            switch (member)
            {
                case IPropertySymbol property when Readable(property):
                    yield return new Candidate(property.Name, property.Type, property.SetMethod is { DeclaredAccessibility: Accessibility.Public, IsInitOnly: false }, false, property);
                    break;
                case IFieldSymbol field when Readable(field):
                    yield return new Candidate(field.Name, field.Type, false, false, field);
                    break;
                case IFieldSymbol field when !field.IsStatic && Marked(field, "CommunityToolkit.Mvvm.ComponentModel.ObservablePropertyAttribute"):
                    yield return new Candidate(ObservableName(field.Name), field.Type, true, true, field);
                    break;
                case IMethodSymbol { MethodKind: MethodKind.Ordinary, IsStatic: false } method when Marked(method, "CommunityToolkit.Mvvm.Input.RelayCommandAttribute"):
                    yield return new Candidate(CommandName(method), null, false, true, method);
                    break;
                case IFieldSymbol field when !field.IsStatic && Attribute(field, ReactiveAttribute) is { } reactive:
                    yield return new Candidate(ObservableName(field.Name), field.Type, PublicSetter(reactive), true, field);
                    break;
                case IMethodSymbol { MethodKind: MethodKind.Ordinary, IsStatic: false } method when Marked(method, ReactiveCommandAttribute):
                    yield return new Candidate(ReactiveCommandName(method), null, false, true, method);
                    break;
            }
        }
    }

    private const string ReactiveAttribute = "ReactiveUI.SourceGenerators.ReactiveAttribute";

    private const string ReactiveCommandAttribute = "ReactiveUI.SourceGenerators.ReactiveCommandAttribute";

    private static bool Marked(ISymbol symbol, string attribute) => Attribute(symbol, attribute) is not null;

    private static AttributeData? Attribute(ISymbol symbol, string attribute) =>
        symbol.GetAttributes().FirstOrDefault(found => found.AttributeClass?.ToDisplayString() == attribute);

    /// <summary>Whether a <c>[Reactive]</c> property's setter is public: no <c>SetModifier</c>, or the one named <c>Public</c>.</summary>
    private static bool PublicSetter(AttributeData reactive) =>
        reactive.NamedArguments.Where(argument => argument.Key == "SetModifier").Select(argument => argument.Value).ToList() is not { Count: 1 } values
        || (values[0].Type is INamedTypeSymbol modifier
            && modifier.GetMembers().OfType<IFieldSymbol>().Any(field => field.HasConstantValue && Equals(field.ConstantValue, values[0].Value) && field.Name == "Public"));

    /// <summary>ReactiveUI.SourceGenerators' command name: the method's, without <c>Async</c> when it returns a <c>Task</c>, and <c>Command</c> after it.</summary>
    private static string ReactiveCommandName(IMethodSymbol method) =>
        (method.Name.Length > 5 && method.Name.EndsWith("Async", StringComparison.Ordinal) && Task(method.ReturnType) ? method.Name.Substring(0, method.Name.Length - 5) : method.Name) + "Command";

    private static string ObservableName(string field)
    {
        var name = field.StartsWith("m_", StringComparison.Ordinal) ? field.Substring(2) : field.TrimStart('_');
        return name.Length == 0 ? field : char.ToUpperInvariant(name[0]) + name.Substring(1);
    }

    private static string CommandName(IMethodSymbol method)
    {
        var name = method.Name;
        if (name.Length > 2 && name.StartsWith("On", StringComparison.Ordinal) && !char.IsLower(name[2]))
        {
            name = name.Substring(2);
        }

        if (method.Name.EndsWith("Async", StringComparison.Ordinal) && Task(method.ReturnType))
        {
            name = name.Substring(0, name.Length - 5);
        }

        return name + "Command";
    }

    internal static bool Task(ITypeSymbol type)
    {
        for (var current = type as INamedTypeSymbol; current is not null; current = current.BaseType)
        {
            if (current.OriginalDefinition.ToDisplayString() == "System.Threading.Tasks.Task")
            {
                return true;
            }
        }

        return false;
    }

    internal sealed class Candidate(string name, ITypeSymbol? type, bool settable, bool generated, ISymbol symbol)
    {
        /// <summary>The member it was found from: a property, a field, or the method of a <c>[RelayCommand]</c>.</summary>
        public ISymbol Symbol { get; } = symbol;

        public string Name { get; } = name;

        public ITypeSymbol? Type { get; } = type;

        public bool Settable { get; } = settable;

        public bool Generated { get; } = generated;
    }

    private static bool SyntaxFacts(string name) => name.Length > 0 && (char.IsLetter(name[0]) || name[0] == '_') && name.All(character => char.IsLetterOrDigit(character) || character == '_');

    private static bool Typeable(Compilation compilation, ITypeSymbol type) =>
        type.TypeKind is not (TypeKind.Dynamic or TypeKind.Error or TypeKind.TypeParameter) && !Contains(type)
        && compilation.IsSymbolAccessibleWithin(type, compilation.Assembly);
}
