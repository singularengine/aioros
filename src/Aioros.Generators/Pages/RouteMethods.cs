using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Aioros.Generators.Pages;

internal static class RouteMethods
{
    private static readonly char[] Slash = ['/'];
    private static readonly char[] WordBreaks = ['-', '_', '.', ' '];

    public static string Emit(IEnumerable<string> routes)
    {
        var used = new HashSet<string>(StringComparer.Ordinal);
        var methods = new StringBuilder();
        foreach (var route in routes.OrderBy(route => route, StringComparer.Ordinal))
        {
            methods.Append(Method(route, used));
        }

        return "// <auto-generated/>\n#nullable enable\n\nnamespace Aioros.Generated;\n\npublic static class Routes\n{\n" + methods + "}\n";
    }

    private static string Method(string route, HashSet<string> used)
    {
        var segments = route.Split(Slash, StringSplitOptions.RemoveEmptyEntries);
        var literals = segments.Where(segment => !segment.StartsWith("{", StringComparison.Ordinal)).Select(Pascal).ToList();
        var parameters = segments.Where(segment => segment.StartsWith("{", StringComparison.Ordinal)).Select(Parameter.Parse).ToList();
        var name = literals.Count == 0 && parameters.Count == 0 ? "Home" : string.Concat(literals);
        if (parameters.Count > 0)
        {
            name += "By" + string.Concat(parameters.Select(parameter => Pascal(parameter.Name)));
        }

        name = Unique(name.Length == 0 ? "Root" : name, used);
        var signature = string.Join(", ", parameters.Select(parameter => parameter.Type + " " + parameter.Identifier));
        var body = segments.Length == 0
            ? "\"/\""
            : string.Join(" + ", segments.Select(segment => "\"/\" + " + Piece(segment)));
        return $"    public static string {name}({signature}) => {body};\n\n";
    }

    private static string Piece(string segment)
    {
        if (!segment.StartsWith("{", StringComparison.Ordinal))
        {
            return "\"" + segment.Replace("\"", "\\\"") + "\"";
        }

        var parameter = Parameter.Parse(segment);
        return parameter.CatchAll
            ? $"string.Join(\"/\", System.Linq.Enumerable.Select({parameter.Identifier}.Split('/'), global::System.Uri.EscapeDataString))"
            : $"global::System.Uri.EscapeDataString({parameter.Text})";
    }

    private static string Unique(string name, HashSet<string> used)
    {
        var index = 1;
        var candidate = name;
        while (!used.Add(candidate))
        {
            index++;
            candidate = name + index.ToString(System.Globalization.CultureInfo.InvariantCulture);
        }

        return candidate;
    }

    private static string Pascal(string text)
    {
        var words = text.Split(WordBreaks, StringSplitOptions.RemoveEmptyEntries);
        var name = string.Concat(words.Select(word => char.ToUpperInvariant(word[0]) + word.Substring(1)));
        name = new string(name.Where(char.IsLetterOrDigit).ToArray());
        return name.Length > 0 && char.IsDigit(name[0]) ? "_" + name : name;
    }

    private sealed class Parameter
    {
        private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
        {
            "class", "event", "object", "string", "int", "long", "bool", "namespace", "public", "static", "base", "this", "params", "default", "operator",
        };

        private Parameter(string name, string constraint, bool catchAll)
        {
            Name = name;
            CatchAll = catchAll;
            Type = constraint switch
            {
                "int" => "int",
                "long" => "long",
                "bool" => "bool",
                "guid" => "global::System.Guid",
                _ => "string",
            };
            var camel = Pascal(name);
            camel = camel.Length == 0 ? "value" : char.ToLowerInvariant(camel[0]) + camel.Substring(1);
            Identifier = Keywords.Contains(camel) ? "@" + camel : camel;
        }

        public string Name { get; }

        public string Type { get; }

        public string Identifier { get; }

        public bool CatchAll { get; }

        public string Text => Type switch
        {
            "string" => Identifier,
            "bool" => $"({Identifier} ? \"true\" : \"false\")",
            _ => $"{Identifier}.ToString(null, global::System.Globalization.CultureInfo.InvariantCulture)",
        };

        public static Parameter Parse(string segment)
        {
            var inner = segment.Trim('{', '}');
            var catchAll = inner.StartsWith("*", StringComparison.Ordinal);
            inner = inner.TrimStart('*');
            var colon = inner.IndexOf(':');
            return colon < 0 ? new Parameter(inner, string.Empty, catchAll) : new Parameter(inner.Substring(0, colon), inner.Substring(colon + 1), catchAll);
        }
    }
}
