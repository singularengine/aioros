using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Aioros.Generators.Plans;

/// <summary>
/// What plans would otherwise find by reflection when the plans file is read, emitted as code: the types plans name,
/// how each command type is run and awaited, and the app's value converters. ASP.NET Core's Request Delegate Generator
/// and the configuration binding generator replace reflection the same way, for the types they can see.
/// </summary>
internal static class PlanCode
{
    public const string TypeEntry = "Aioros.Runtime.Slots.PlanType";
    public const string CommandEntry = "Aioros.Runtime.Slots.CommandShape";
    public const string ConverterEntry = "Aioros.Runtime.Slots.ConverterCode";
    public const string ValueConverter = "Avalonia.Data.Converters.IValueConverter";
    public const string MultiValueConverter = "Avalonia.Data.Converters.IMultiValueConverter";

    private const string Header = "// <auto-generated/>\n#nullable disable\n\nnamespace Aioros.Generated\n{\n";

    private static readonly string[] TargetTypes =
    [
        "Avalonia.Media.IBrush", "Avalonia.Media.IImage", "Avalonia.Thickness", "Avalonia.CornerRadius", "Avalonia.Media.FontWeight",
        "Avalonia.Media.FontStyle", "Avalonia.Layout.HorizontalAlignment", "Avalonia.Layout.VerticalAlignment", "Avalonia.Layout.Orientation",
        "Avalonia.Media.TextAlignment", "Avalonia.Media.TextWrapping", "Avalonia.Controls.Dock", "Avalonia.Media.Geometry",
    ];

    private static readonly string[] BuiltinConverters =
    [
        "Avalonia.Data.Converters.BoolConverters", "Avalonia.Data.Converters.ObjectConverters", "Avalonia.Data.Converters.StringConverters",
    ];

    private static readonly SymbolDisplayFormat Full = SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(
        SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions | SymbolDisplayMiscellaneousOptions.ExpandValueTuple);

    public static bool EmitsTypes(Compilation compilation) => compilation.GetTypeByMetadataName(TypeEntry) is not null;

    public static bool EmitsCommands(Compilation compilation) => compilation.GetTypeByMetadataName(CommandEntry) is not null;

    public static bool EmitsConverters(Compilation compilation) =>
        compilation.GetTypeByMetadataName(ConverterEntry) is not null && compilation.GetTypeByMetadataName(ValueConverter) is not null;

    /// <summary>The types the XAML names as data types and the binding target types converters are given, each returned only when asked for.</summary>
    public static string Types(Compilation compilation, IEnumerable<string> dataTypes)
    {
        var types = dataTypes.Concat(TargetTypes).Distinct(StringComparer.Ordinal)
            .Select(compilation.GetTypeByMetadataName).OfType<INamedTypeSymbol>()
            .Where(type => !type.IsUnboundGenericType && type.TypeParameters.IsEmpty && compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
            .OrderBy(MetadataName, StringComparer.Ordinal);
        var code = new StringBuilder(Header)
            .Append("    internal static class AiorosTypes\n    {\n")
            .Append("        public static global::System.Collections.Immutable.ImmutableArray<global::Aioros.Runtime.Slots.PlanType> All { get; } =\n        [\n");
        foreach (var type in types)
        {
            code.Append("            new(\"").Append(MetadataName(type)).Append("\", static () => typeof(").Append(type.ToDisplayString(Full)).Append(")),\n");
        }

        return code.Append("        ];\n    }\n}\n").ToString();
    }

    /// <summary>A runner per command type the view models expose, the awaitable and observable shapes before the plain ones.</summary>
    public static string Commands(Compilation compilation, IEnumerable<string> dataTypes)
    {
        var roots = dataTypes.Distinct(StringComparer.Ordinal).Select(compilation.GetTypeByMetadataName).OfType<ITypeSymbol>();
        var command = compilation.GetTypeByMetadataName("System.Windows.Input.ICommand");
        var found = new List<ITypeSymbol>();
        foreach (var owner in PlanAccessors.Owners(compilation, roots).Where(owner => owner is not IArrayTypeSymbol && !PlanAccessors.Framework(owner)))
        {
            foreach (var candidate in PlanAccessors.Candidates([.. PlanAccessors.Hierarchy(owner).SelectMany(type => type.GetMembers())]))
            {
                found.AddRange(candidate.Symbol is IMethodSymbol method ? Toolkit(compilation, method) : Commanding(candidate.Type, command));
            }
        }

        var shapes = found.Distinct<ITypeSymbol>(SymbolEqualityComparer.Default)
            .Where(type => compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
            .Select(type => (Type: type, Shape: Shape(compilation, type)))
            .Where(entry => entry.Shape is not null)
            .OrderBy(entry => entry.Shape!.Value.Plain ? 1 : 0)
            .ThenBy(entry => entry.Type.ToDisplayString(Full), StringComparer.Ordinal);
        var code = new StringBuilder(Header)
            .Append("    internal static class AiorosCommands\n    {\n")
            .Append("        public static global::System.Collections.Immutable.ImmutableArray<global::Aioros.Runtime.Slots.CommandShape> All { get; } =\n        [\n");
        foreach (var (type, shape) in shapes)
        {
            code.Append("            new(typeof(").Append(type.ToDisplayString(Full)).Append("), static (command, parameter) => ").Append(shape!.Value.Run)
                .Append(shape.Value.Plain ? ") { Exact = true },\n" : "),\n");
        }

        return code.Append("        ];\n    }\n}\n").ToString();
    }

    /// <summary>
    /// The app's converters by the reference the plans file names them with: the public static members of Avalonia's
    /// built-in converter classes and of the app's converter classes, and each app converter class that can be created
    /// with no settings, with how Avalonia runs them; the converters other app classes hold in public static members
    /// (a static class of <c>FuncValueConverter</c>s); and the app's public static lists (<c>x:Static</c> items of a
    /// <c>ComboBox</c>) by the same kind of reference.
    /// </summary>
    public static string Converters(Compilation compilation)
    {
        var value = compilation.GetTypeByMetadataName(ValueConverter)!;
        var multi = compilation.GetTypeByMetadataName(MultiValueConverter);
        var enumerable = compilation.GetSpecialType(SpecialType.System_Collections_IEnumerable);
        bool IsConverter(ITypeSymbol type) => Is(type, value) || Is(type, multi);
        bool IsList(ITypeSymbol type) => type.SpecialType != SpecialType.System_String && (type is IArrayTypeSymbol || Is(type, enumerable));
        bool Referenced(ISymbol member) => Holds(member, IsConverter) || Holds(member, IsList);
        var owners = BuiltinConverters.Select(compilation.GetTypeByMetadataName).OfType<INamedTypeSymbol>()
            .Concat(Pages.PageLoaders.Types(compilation.Assembly.GlobalNamespace).Where(type => type.TypeKind == TypeKind.Class && (IsConverter(type) || !type.IsGenericType && type.GetMembers().Any(member => PublicStatic(member) && Referenced(member)))))
            .Where(type => compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
            .Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)
            .OrderBy(MetadataName, StringComparer.Ordinal);
        var code = new StringBuilder(Header)
            .Append("    internal static class AiorosConverters\n    {\n")
            .Append("        public static global::Aioros.Runtime.Slots.ConverterCode Code { get; } = new(\n            [\n");
        foreach (var owner in owners)
        {
            var name = owner.ToDisplayString(Full);
            foreach (var member in owner.GetMembers().Where(member => PublicStatic(member) && Referenced(member)).Select(member => member.Name).OrderBy(member => member, StringComparer.Ordinal))
            {
                code.Append("                new(\"static:").Append(MetadataName(owner)).Append(':').Append(member).Append("\", static () => ").Append(name).Append('.').Append(member).Append("),\n");
            }

            if (IsConverter(owner) && Creatable(owner))
            {
                code.Append("                new(\"type:").Append(MetadataName(owner)).Append("\", static () => new ").Append(name).Append("()),\n");
            }
        }

        return code.Append("""
                        ],
                        static (converter, value, target, parameter, culture) => Settle(((global::Avalonia.Data.Converters.IValueConverter)converter).Convert(value, target, parameter, culture)),
                        static (converter, values, target, parameter, culture) => SettleMany(((global::Avalonia.Data.Converters.IMultiValueConverter)converter).Convert(values, target, parameter, culture)),
                        static (format, inner) => new global::Avalonia.Data.Converters.StringFormatMultiValueConverter(format, (global::Avalonia.Data.Converters.IMultiValueConverter)inner));

                    private static object Settle(object value) =>
                        value is global::Avalonia.Data.BindingNotification || value == global::Avalonia.AvaloniaProperty.UnsetValue ? null : value;

                    private static object SettleMany(object value)
                    {
                        var settled = global::Avalonia.Data.BindingNotification.ExtractValue(value);
                        return settled == global::Avalonia.AvaloniaProperty.UnsetValue || settled == global::Avalonia.Data.BindingOperations.DoNothing ? null : settled;
                    }
                }
            }

            """).ToString();
    }

    /// <summary>The name a type has in an assembly-qualified name: its namespace, and nested types joined with <c>+</c>.</summary>
    private static bool Is(ITypeSymbol type, ITypeSymbol? face) =>
        face is not null && (SymbolEqualityComparer.Default.Equals(type, face) || type.AllInterfaces.Any(item => SymbolEqualityComparer.Default.Equals(item, face)));

    private static bool PublicStatic(ISymbol member) =>
        member.IsStatic && member.DeclaredAccessibility == Accessibility.Public && !member.GetAttributes().Any(attribute => attribute.AttributeClass?.Name == nameof(ObsoleteAttribute));

    private static bool Holds(ISymbol member, Func<ITypeSymbol, bool> kind) =>
        member is IFieldSymbol { Type: var fieldType } && kind(fieldType)
        || member is IPropertySymbol { IsIndexer: false, GetMethod.DeclaredAccessibility: Accessibility.Public, Type: var propertyType } && kind(propertyType);

    public static string MetadataName(INamedTypeSymbol type) =>
        type.ContainingType is { } outer ? MetadataName(outer) + "+" + type.MetadataName
        : type.ContainingNamespace is { IsGlobalNamespace: false } space ? space.ToDisplayString() + "." + type.MetadataName
        : type.MetadataName;

    /// <summary>A converter class Avalonia's adapter can rebuild: a public parameterless constructor and no property that can be set.</summary>
    private static bool Creatable(INamedTypeSymbol type) =>
        !type.IsAbstract && !type.IsStatic
        && type.InstanceConstructors.Any(constructor => constructor.Parameters.IsEmpty && constructor.DeclaredAccessibility == Accessibility.Public)
        && !PlanAccessors.Hierarchy(type).SelectMany(owner => owner.GetMembers()).OfType<IPropertySymbol>()
            .Any(property => !property.IsStatic && property.DeclaredAccessibility == Accessibility.Public && property.SetMethod is not null);

    private static IEnumerable<ITypeSymbol> Commanding(ITypeSymbol? type, INamedTypeSymbol? command) =>
        type is not null && command is not null && (SymbolEqualityComparer.Default.Equals(type, command) || type.AllInterfaces.Contains(command, SymbolEqualityComparer.Default))
            ? [type.WithNullableAnnotation(NullableAnnotation.NotAnnotated)]
            : [];

    /// <summary>
    /// The command types CommunityToolkit creates for a <c>[RelayCommand]</c> method, by its rules: an awaitable method gets
    /// an <c>AsyncRelayCommand</c> (generic over its parameter), any other a <c>RelayCommand</c>; a trailing
    /// <c>CancellationToken</c> is not a parameter. The interface is kept too, which every one of them is.
    /// </summary>
    private static IEnumerable<ITypeSymbol> Toolkit(Compilation compilation, IMethodSymbol method)
    {
        var parameters = method.Parameters.Where(parameter => parameter.Type.ToDisplayString() != "System.Threading.CancellationToken").ToList();
        var awaitable = PlanAccessors.Task(method.ReturnType);
        var (concrete, contract) = awaitable ? ("AsyncRelayCommand", "IAsyncRelayCommand") : ("RelayCommand", "IRelayCommand");
        foreach (var name in new[] { concrete, contract })
        {
            var type = compilation.GetTypeByMetadataName("CommunityToolkit.Mvvm.Input." + name + (parameters.Count == 1 ? "`1" : string.Empty));
            if (type is not null && parameters.Count <= 1)
            {
                yield return parameters.Count == 1 ? type.Construct(parameters[0].Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated)) : type;
            }
        }
    }

    private readonly struct Runner(string run, bool plain)
    {
        public string Run { get; } = run;

        public bool Plain { get; } = plain;
    }

    /// <summary>
    /// How a command type is run, as <c>AwaitedCommands</c> finds it by reflection: a public awaitable
    /// <c>ExecuteAsync(object)</c> on the type or one of its interfaces, else a public <c>Execute(TParam)</c> returning an
    /// <c>IObservable&lt;T&gt;</c>, else plain <c>Execute</c>, kept only for a class it matches exactly.
    /// </summary>
    private static Runner? Shape(Compilation compilation, ITypeSymbol type)
    {
        var name = type.ToDisplayString(Full);
        var methods = PlanAccessors.Hierarchy(type).SelectMany(owner => owner.GetMembers()).OfType<IMethodSymbol>()
            .Where(method => method.DeclaredAccessibility == Accessibility.Public && !method.IsStatic).ToList();
        var awaitable = methods.Select(method => (Method: method, Owner: name))
            .Concat(type.AllInterfaces.SelectMany(face => face.GetMembers().OfType<IMethodSymbol>().Select(method => (Method: method, Owner: face.ToDisplayString(Full)))))
            .FirstOrDefault(entry => entry.Method is { Name: "ExecuteAsync", IsStatic: false } && entry.Method.Parameters.Length == 1
                && entry.Method.Parameters[0].Type.SpecialType == SpecialType.System_Object && Awaited(entry.Method.ReturnType, "x") is not null);
        if (awaitable.Method is not null)
        {
            return new Runner(Awaited(awaitable.Method.ReturnType, "((" + awaitable.Owner + ")command).ExecuteAsync(parameter)")!, false);
        }

        foreach (var method in methods.Where(method => method is { Name: "Execute", Parameters.Length: 1 }))
        {
            if (Observed(method.ReturnType) is { } element)
            {
                var parameter = method.Parameters[0].Type.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString(Full);
                return new Runner(
                    "global::Aioros.Runtime.Slots.PlanCommands.ObserveAsync<" + element.ToDisplayString(Full) + ">(((" + name + ")command).Execute(parameter is null ? default(" + parameter + ") : (" + parameter + ")parameter))",
                    false);
            }
        }

        return type.TypeKind == TypeKind.Class && !type.IsAbstract && compilation.IsSymbolAccessibleWithin(type, compilation.Assembly)
            ? new Runner("{ command.Execute(parameter); return default; }", true)
            : null;
    }

    internal static string? Awaited(ITypeSymbol returned, string call)
    {
        var definition = returned.OriginalDefinition.ToDisplayString();
        if (definition == "System.Threading.Tasks.ValueTask")
        {
            return call;
        }

        if (PlanAccessors.Task(returned))
        {
            return "new global::System.Threading.Tasks.ValueTask(" + call + ")";
        }

        return definition == "System.Threading.Tasks.ValueTask<TResult>"
            ? "global::Aioros.Runtime.Slots.PlanCommands.AwaitAsync(" + call + ")"
            : null;
    }

    private static ITypeSymbol? Observed(ITypeSymbol returned) =>
        new[] { returned }.Concat(returned.AllInterfaces)
            .OfType<INamedTypeSymbol>()
            .FirstOrDefault(candidate => candidate.IsGenericType && candidate.MetadataName == "IObservable`1" && candidate.ContainingNamespace?.ToDisplayString() == "System")?
            .TypeArguments[0];
}
