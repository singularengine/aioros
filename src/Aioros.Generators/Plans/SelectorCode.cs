using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Aioros.Generators.Plans;

/// <summary>
/// The app's template selectors (its own <c>IDataTemplate</c> classes that hold templates), emitted as code that rebuilds
/// each from a plans file's entries with a stand-in template per entry and asks its own <c>Match</c> and <c>Build</c>
/// which one an item takes, so a plan maps the choice to the template it learned without reflection or Avalonia's
/// platform. MAUI's and WinUI's <c>DataTemplateSelector</c> run the app's selector the same way and map the template it returns.
/// </summary>
internal static class SelectorCode
{
    public const string SelectorEntry = "Aioros.Runtime.Slots.SelectorCode";
    public const string DataTemplate = "Avalonia.Controls.Templates.IDataTemplate";

    private const string Mark = "global::Aioros.Generated.AiorosTemplateMark";

    private static readonly SymbolDisplayFormat Full = SymbolDisplayFormat.FullyQualifiedFormat;

    public static bool Emits(Compilation compilation) =>
        compilation.GetTypeByMetadataName(SelectorEntry) is not null && compilation.GetTypeByMetadataName(DataTemplate) is not null;

    public static string Emit(Compilation compilation)
    {
        var template = compilation.GetTypeByMetadataName(DataTemplate)!;
        var selectors = Pages.PageLoaders.Types(compilation.Assembly.GlobalNamespace)
            .Where(type => type.TypeKind == TypeKind.Class && !type.IsAbstract && !type.IsGenericType && Implements(type, template)
                && compilation.IsSymbolAccessibleWithin(type, compilation.Assembly)
                && type.InstanceConstructors.Any(constructor => constructor.Parameters.IsEmpty && constructor.DeclaredAccessibility == Accessibility.Public))
            .Select(type => (Type: type, Members: Members(type, template)))
            .Where(entry => entry.Members is { Count: > 0 })
            .OrderBy(entry => PlanCode.MetadataName(entry.Type), System.StringComparer.Ordinal)
            .ToList();
        var code = new StringBuilder("// <auto-generated/>\n#nullable disable\n\nnamespace Aioros.Generated\n{\n")
            .Append("    internal static class AiorosSelectors\n    {\n")
            .Append("        public static global::System.Collections.Immutable.ImmutableArray<global::Aioros.Runtime.Slots.SelectorCode> All { get; } =\n        [\n");
        foreach (var (type, members) in selectors)
        {
            code.Append("            new(\"").Append(PlanCode.MetadataName(type)).Append("\", static entries =>\n            {\n")
                .Append("                var selector = new ").Append(type.ToDisplayString(Full)).Append("();\n")
                .Append("                for (var index = 0; index < entries.Length; index++)\n                {\n")
                .Append("                    var entry = entries[index];\n")
                .Append("                    var mark = new ").Append(Mark).Append("(index);\n")
                .Append("                    switch (entry.Member)\n                    {\n");
            foreach (var member in members!)
            {
                code.Append("                        case \"").Append(member.Name).Append("\":\n                        {\n").Append(member.Set).Append("                            break;\n                        }\n");
            }

            code.Append("                        default:\n                            return null;\n                    }\n                }\n\n")
                .Append("                return item => ").Append(Mark).Append(".Choose(selector, item);\n            }),\n");
        }

        code.Append("        ];\n    }\n");
        if (selectors.Count == 0)
        {
            return code.Append("}\n").ToString();
        }

        return code.Append("""

                internal sealed class AiorosTemplateMark(int index) : global::Avalonia.Controls.Templates.IDataTemplate
                {
                    [global::System.ThreadStatic]
                    private static int _chosen;

                    public static int Choose(global::Avalonia.Controls.Templates.IDataTemplate selector, object item)
                    {
                        if (!selector.Match(item))
                        {
                            return -1;
                        }

                        _chosen = -1;
                        selector.Build(item);
                        return _chosen;
                    }

                    public global::Avalonia.Controls.Control Build(object param)
                    {
                        _chosen = index;
                        return null;
                    }

                    public bool Match(object data) => true;
                }
            }

            """).ToString();
    }

    private readonly struct Member(string name, string set)
    {
        public string Name { get; } = name;

        public string Set { get; } = set;
    }

    /// <summary>
    /// How each template the selector holds is set: an <c>IDataTemplate</c> property by assignment, a dictionary of
    /// templates by its key parsed from the entry; nothing when another public property can be set, which a plan cannot rebuild.
    /// </summary>
    private static List<Member>? Members(INamedTypeSymbol type, INamedTypeSymbol template)
    {
        var members = new List<Member>();
        var properties = PlanAccessors.Hierarchy(type).SelectMany(owner => owner.GetMembers()).OfType<IPropertySymbol>()
            .Where(property => !property.IsStatic && !property.IsIndexer && property.DeclaredAccessibility == Accessibility.Public);
        foreach (var property in properties)
        {
            var settable = property.SetMethod is { DeclaredAccessibility: Accessibility.Public, IsInitOnly: false };
            if (settable && Implements(property.Type, template))
            {
                members.Add(new Member(property.Name, "                            selector." + property.Name + " = mark;\n"));
            }
            else if (Dictionary(property.Type, template) is { } key && Key(key) is { } parse)
            {
                members.Add(new Member(property.Name, parse.Replace("{set}", "selector." + property.Name)));
            }
            else if (settable)
            {
                return null;
            }
        }

        return members;
    }

    private static ITypeSymbol? Dictionary(ITypeSymbol type, INamedTypeSymbol template) =>
        new[] { type }.Concat(type.AllInterfaces).OfType<INamedTypeSymbol>()
            .FirstOrDefault(face => face.IsGenericType && face.ConstructedFrom.ToDisplayString() == "System.Collections.Generic.IDictionary<TKey, TValue>"
                && SymbolEqualityComparer.Default.Equals(face.TypeArguments[1].WithNullableAnnotation(NullableAnnotation.NotAnnotated), template))?
            .TypeArguments[0];

    private static string? Key(ITypeSymbol key)
    {
        const string Indent = "                            ";
        if (key.SpecialType == SpecialType.System_String)
        {
            return Indent + "{set}[entry.Key] = mark;\n";
        }

        if (key.SpecialType == SpecialType.System_Int32)
        {
            return Indent + "{set}[int.Parse(entry.Key, global::System.Globalization.CultureInfo.InvariantCulture)] = mark;\n";
        }

        if (key.ToDisplayString() == "System.Type")
        {
            return Indent + "if (global::Aioros.Runtime.Slots.PlanTypes.Find(entry.Key) is not { } type)\n" + Indent + "{\n" + Indent + "    return null;\n" + Indent + "}\n\n" + Indent + "{set}[type] = mark;\n";
        }

        return key.TypeKind == TypeKind.Enum ? Indent + "{set}[global::System.Enum.Parse<" + key.ToDisplayString(Full) + ">(entry.Key)] = mark;\n" : null;
    }

    private static bool Implements(ITypeSymbol type, INamedTypeSymbol face) =>
        SymbolEqualityComparer.Default.Equals(type.WithNullableAnnotation(NullableAnnotation.NotAnnotated), face) || type.AllInterfaces.Contains(face, SymbolEqualityComparer.Default);
}
