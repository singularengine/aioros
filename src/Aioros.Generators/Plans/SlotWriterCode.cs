using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Aioros.Generators.Plans;

/// <summary>
/// The slot writers and renderers the app and its libraries declare (<c>[assembly: SlotWriter&lt;T&gt;]</c>,
/// <c>[assembly: SlotRenderer&lt;T&gt;]</c>), emitted as entries that create each through its type's static <c>Create</c>
/// (a writer's adapted to a renderer that writes the value alone) and a renderer's decoder of its composite fields' posts,
/// so the runtime finds a plan's writer by name without reflection. Avalonia's XAML compiler reads a library's
/// <c>XmlnsDefinition</c> assembly attributes at build time the same way.
/// </summary>
internal static class SlotWriterCode
{
    public const string Entry = "Aioros.Runtime.Rendering.SlotWriterEntry";
    public const string Attribute = "Aioros.Runtime.Rendering.SlotWriterAttribute`1";
    public const string RendererAttribute = "Aioros.Runtime.Rendering.SlotRendererAttribute`1";

    private static readonly SymbolDisplayFormat Full = SymbolDisplayFormat.FullyQualifiedFormat;

    public static bool Emits(Compilation compilation) =>
        compilation.GetTypeByMetadataName(Entry) is not null && compilation.GetTypeByMetadataName(Attribute) is not null;

    public static string Emit(Compilation compilation)
    {
        var writer = compilation.GetTypeByMetadataName(Attribute);
        var renderer = compilation.GetTypeByMetadataName(RendererAttribute);
        var declared = new[] { compilation.Assembly }.Concat(compilation.SourceModule.ReferencedAssemblySymbols)
            .SelectMany(assembly => assembly.GetAttributes())
            .Select(data => data.AttributeClass)
            .Where(type => type is { IsGenericType: true })
            .Select(type => (Type: type!.TypeArguments[0] as INamedTypeSymbol, Renders: renderer is not null && SymbolEqualityComparer.Default.Equals(type.OriginalDefinition, renderer), Writes: SymbolEqualityComparer.Default.Equals(type.OriginalDefinition, writer)))
            .Where(entry => entry.Type is not null && (entry.Renders || entry.Writes) && compilation.IsSymbolAccessibleWithin(entry.Type, compilation.Assembly))
            .GroupBy(entry => PlanCode.MetadataName(entry.Type!), System.StringComparer.Ordinal)
            .Select(group => group.First())
            .OrderBy(entry => PlanCode.MetadataName(entry.Type!), System.StringComparer.Ordinal);
        var code = new StringBuilder("// <auto-generated/>\n#nullable disable\n\nnamespace Aioros.Generated\n{\n")
            .Append("    internal static class AiorosSlotWriters\n    {\n")
            .Append("        public static global::System.Collections.Immutable.ImmutableArray<global::Aioros.Runtime.Rendering.SlotWriterEntry> All { get; } =\n        [\n");
        foreach (var (type, renders, _) in declared)
        {
            var name = type!.ToDisplayString(Full);
            code.Append("            new(\"").Append(PlanCode.MetadataName(type)).Append("\", ")
                .Append(renders ? name + ".Create) { Decode = global::Aioros.Runtime.Rendering.SlotWriters.Decoder<" + name + ">() }" : "global::Aioros.Runtime.Rendering.SlotWriters.Rendering<" + name + ">())")
                .Append(",\n");
        }

        return code.Append("        ];\n    }\n}\n").ToString();
    }
}
