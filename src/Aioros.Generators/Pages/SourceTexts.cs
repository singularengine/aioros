using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Aioros.Generators.Pages;

internal static class SourceTexts
{
    public static string Emit(IEnumerable<(string Path, string Text)> files)
    {
        var code = new StringBuilder()
            .Append("// <auto-generated />\n#nullable enable\nnamespace Aioros.Generated;\n\n")
            .Append("/// <summary>The XAML of the app's pages and layouts, embedded because AiorosEmbedSources is true.</summary>\n")
            .Append("public static class AiorosSources\n{\n    public static string? Text(string path) => path switch\n    {\n");
        foreach (var (path, text) in files.GroupBy(file => file.Path).Select(group => group.First()).OrderBy(file => file.Path, System.StringComparer.Ordinal))
        {
            code.Append("        ").Append(Literal(path)).Append(" => ").Append(Literal(text)).Append(",\n");
        }

        return code.Append("        _ => null,\n    };\n}\n").ToString();
    }

    private static string Literal(string text) => "@\"" + text.Replace("\"", "\"\"") + "\"";
}
