using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Aioros.Generators.Plans;

/// <summary>
/// The icon sets the app and its libraries declare (<c>[assembly: IconSet&lt;T&gt;]</c>, the attribute matched by its full
/// name), emitted as one list of their
/// icons that the host registers when it starts, so a library's icons reach the <c>Icon</c> control on every target
/// without reflection, as slot writers do.
/// </summary>
internal static class IconSetCode
{
    public const string Attribute = "Aioros.Icons.IconSetAttribute`1";

    private static readonly SymbolDisplayFormat Full = SymbolDisplayFormat.FullyQualifiedFormat;

    public static bool Emits(Compilation compilation) => !compilation.GetTypesByMetadataName(Attribute).IsEmpty;

    /// <summary>
    /// Whether an attribute is the icon set declaration by its full name: the abstractions' own, or a library's copy of it
    /// (a library that references only Avalonia declares <c>Aioros.Icons.IconSetAttribute&lt;T&gt;</c> itself, as the
    /// compiler recognizes polyfilled attributes such as <c>IsExternalInit</c> by name).
    /// </summary>
    private static bool Named(INamedTypeSymbol type) =>
        type.ContainingNamespace?.ToDisplayString() + "." + type.MetadataName == Attribute;

    public static string Emit(Compilation compilation)
    {
        var sets = new[] { compilation.Assembly }.Concat(compilation.SourceModule.ReferencedAssemblySymbols)
            .SelectMany(assembly => assembly.GetAttributes())
            .Select(data => data.AttributeClass)
            .Where(type => type is { IsGenericType: true } && Named(type.OriginalDefinition))
            .Select(type => type!.TypeArguments[0] as INamedTypeSymbol)
            .Where(type => type is not null && compilation.IsSymbolAccessibleWithin(type, compilation.Assembly))
            .GroupBy(type => PlanCode.MetadataName(type!), System.StringComparer.Ordinal)
            .Select(group => group.First()!)
            .OrderBy(type => PlanCode.MetadataName(type), System.StringComparer.Ordinal)
            .ToList();
        var code = new StringBuilder("// <auto-generated/>\n#nullable disable\n\nnamespace Aioros.Generated\n{\n")
            .Append("    internal static class AiorosIcons\n    {\n")
            .Append("        public static global::System.Collections.Immutable.ImmutableArray<global::System.Collections.Generic.KeyValuePair<string, string>> All { get; } =\n        [\n");
        foreach (var set in sets)
        {
            code.Append("            .. ").Append(set.ToDisplayString(Full)).Append(".Icons,\n");
        }

        return code.Append("        ];\n    }\n}\n").ToString();
    }
}
