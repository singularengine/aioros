using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Aioros.Routing.Files;
using Microsoft.CodeAnalysis;

namespace Aioros.Generators.Pages;

internal sealed class RegistryEmitter(INamedTypeSymbol? application, string directory, DataShapes shapes, string? viewError = null, bool switched = false, Compilation? compilation = null)
{
    private const string Supported = "global::Aioros.Pages.PageEngines.AvaloniaIsSupported";

    private const string Header = "// <auto-generated/>\n#nullable enable\n\nnamespace Aioros.Generated;\n\n";
    private const string Provider = "global::System.IServiceProvider";

    public static string EntryPoint(string returnType, string? server = null, string? generated = null) => $$"""
        // <auto-generated/>
        #nullable enable

        internal static class AiorosApplication
        {
            public static {{returnType}} CreateBuilder(string[] args) =>
                global::Aioros.Hosting.AiorosHost.CreateBuilder(
                    args,
                    new global::Aioros.Hosting.AiorosApp(
                        global::Aioros.Generated.AiorosPages.All,
                        global::Aioros.Generated.AiorosPages.ApplicationType,
                        typeof(global::Aioros.Generated.AiorosPages).Assembly,
                        global::Aioros.Generated.AiorosPages.ProjectDirectory,
                        global::Aioros.Generated.AiorosPages.NotFound,
                        global::Aioros.Generated.AiorosPages.Error)
                    {
                        Functions = global::Aioros.Generated.AiorosFunctions.All,
                        Navigators = global::Aioros.Generated.AiorosNavigators.All,
                        Accessors = global::Aioros.Generated.AiorosAccessors.All,{{generated}}{{(server is null ? string.Empty : "\n                        Server = " + Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(server, true) + ",")}}
                    });
        }
        """;

    private readonly AvaloniaModels? _avalonia = compilation is null ? null : new AvaloniaModels(compilation);
    private readonly AnywhereCommands? _anywhere = compilation is null ? null : new AnywhereCommands(compilation);
    private readonly StringBuilder _pages = new();
    private string _notFound = "null";
    private string _error = "null";
    private string _nativeOnly = "null";
    private readonly StringBuilder _factories = new();
    private int _factoryCount;
    private readonly Dictionary<string, string> _loaders = new(StringComparer.Ordinal);
    private readonly List<DataShape> _codecs = [];

    private readonly StringBuilder _views = new();
    private readonly Dictionary<string, string> _viewFields = new(StringComparer.Ordinal);

    public void Add(FileRoute route, (INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head) page, IReadOnlyList<(string Source, (INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head) Model)> layouts, IReadOnlyList<PlacedView> views, string? platforms = null, IReadOnlyDictionary<string, (string Path, string Text)>? sources = null) =>
        _pages.Append("        ").Append(Definition(route, page, layouts, views, platforms, sources is null ? null : _anywhere?.Of(route, views, sources))).Append(",\n");

    public void SetNativeOnly(FileRoute route, (INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head) page, IReadOnlyList<(string Source, (INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head) Model)> layouts, IReadOnlyList<PlacedView> views) =>
        _nativeOnly = Definition(route, page, layouts, views);

    public void SetNotFound(FileRoute route, (INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head) page, IReadOnlyList<(string Source, (INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head) Model)> layouts, IReadOnlyList<PlacedView> views) =>
        _notFound = Definition(route, page, layouts, views);

    public void SetError(FileRoute route, (INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head) page, IReadOnlyList<(string Source, (INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head) Model)> layouts, IReadOnlyList<PlacedView> views) =>
        _error = Definition(route, page, layouts, views);

    private string Definition(FileRoute route, (INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head) page, IReadOnlyList<(string Source, (INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head) Model)> layouts, IReadOnlyList<PlacedView> views, string? platforms = null, IReadOnlyList<string>? commands = null)
    {
        var layoutList = string.Join(", ", layouts.Select(layout =>
        {
            var members = new List<string>();
            if (layout.Model.Loader is not null)
            {
                members.Add("Loader = " + Loader(layout.Source, layout.Model.Type, layout.Model.Loader));
            }

            if (layout.Model.Head is not null)
            {
                members.Add("Head = " + layout.Model.Head);
            }

            return $"new global::Aioros.Pages.LayoutDefinition({Literal(layout.Source)}, {Factory(layout.Model.Type, layout.Model.Loader)})"
                + (members.Count == 0 ? string.Empty : " { " + string.Join(", ", members) + " }");
        }));
        var initializers = new List<string>();
        if (page.Head is not null)
        {
            initializers.Add("Head = " + page.Head);
        }

        if (platforms is not null)
        {
            initializers.Add("Platforms = " + platforms);
        }

        if (Allows(page.Loader?.Type) || Allows(page.Type))
        {
            initializers.Add("AllowAnonymous = true");
        }
        else if (Access(layouts.Select(layout => layout.Model).Append(page)) is { Count: > 0 } access)
        {
            initializers.Add("Access = [" + string.Join(", ", access) + "]");
        }

        if (page.Loader is not null)
        {
            initializers.Add("Loader = " + Loader(route.Source, page.Type, page.Loader));
        }

        initializers.AddRange(Threads(page, layouts, views, commands));

        initializers.Add("DataContract = \"" + Contract(layouts.Select(layout => layout.Model.Loader).Append(page.Loader), views) + "\"");
        initializers.AddRange(ViewMembers(views));

        return "new global::Aioros.Pages.PageDefinition(" + Literal(route.Route) + ", " + Literal(route.Source) + ", " + Factory(page.Type, page.Loader)
            + ", [" + layoutList + "], " + (page.Live ? "true" : "false") + ")"
            + (initializers.Count == 0 ? string.Empty : " { " + string.Join(", ", initializers) + " }");
    }

    /// <summary>Where the page's models are created and its commands run: on Avalonia's thread when the models use Avalonia, and the commands that run on any thread.</summary>
    private IEnumerable<string> Threads((INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head) page, IReadOnlyList<(string Source, (INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head) Model)> layouts, IReadOnlyList<PlacedView> views, IReadOnlyList<string>? commands)
    {
        if (UsesAvalonia(layouts.Select(layout => layout.Model).Append(page).Concat(views.Select(view => view.Model))))
        {
            yield return "ModelsUseAvalonia = true";
        }

        if (commands is { Count: > 0 })
        {
            yield return "AnywhereCommands = [" + string.Join(", ", commands.Select(Literal)) + "]";
        }
    }

    private bool UsesAvalonia(IEnumerable<(INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head)> models) =>
        _avalonia is { } avalonia && models.Any(model => avalonia.Use(model.Type) || avalonia.Loads(model.Loader));

    private string Contract(IEnumerable<PageLoader?> segments, IReadOnlyList<PlacedView> views) =>
        DataCodecs.Hash(string.Join("|", segments.Select((loader, index) => (data: loader?.Data, index)).Where(segment => segment.data is not null)
            .Select(segment => segment.index.ToString(System.Globalization.CultureInfo.InvariantCulture) + ":" + shapes.Describe(segment.data!))
            .Concat(views.Where(view => view.Model.Loader?.Data is not null).Select(view => view.Key + ":" + shapes.Describe(view.Model.Loader!.Data!)))));

    private IEnumerable<string> ViewMembers(IReadOnlyList<PlacedView> views)
    {
        if (views.Count == 0)
        {
            yield break;
        }

        yield return "Views = [" + string.Join(", ", views.Select(view =>
            $"new global::Aioros.Pages.ViewInstance({Literal(view.Key)}, {view.Segment}, {ViewField(view)})" + Initializers(view))) + "]";
        if (viewError is not null)
        {
            yield return "ViewError = " + Literal(viewError);
        }
    }

    private static string Initializers(PlacedView view)
    {
        var members = new List<string>();
        if (view.Parent >= 0)
        {
            members.Add($"Parent = {view.Parent}");
        }

        if (view.List is not null)
        {
            members.Add("List = " + view.List);
        }

        return members.Count == 0 ? string.Empty : " { " + string.Join(", ", members) + " }";
    }

    private string ViewField(PlacedView view)
    {
        if (_viewFields.TryGetValue(view.Source, out var known))
        {
            return known;
        }

        var name = "View" + _viewFields.Count.ToString(System.Globalization.CultureInfo.InvariantCulture);
        _viewFields[view.Source] = name;
        var members = new List<string>();
        if (view.Class is not null)
        {
            members.Add($"Type = {Lazy(view.Class)}");
        }

        if (view.Model.Loader is { } loader)
        {
            members.Add("Loader = " + Loader(view.Source, view.Model.Type, loader));
            if (Access([view.Model]) is { Count: > 0 } access && !Allows(loader.Type))
            {
                members.Add("Access = [" + string.Join(", ", access) + "]");
            }
        }

        _views.Append($"    private static readonly global::Aioros.Pages.ViewDefinition {name} = new global::Aioros.Pages.ViewDefinition({Literal(view.Source)}, {Factory(view.Model.Type, view.Model.Loader)})"
            + (members.Count == 0 ? string.Empty : " { " + string.Join(", ", members) + " }") + ";\n\n");
        return name;
    }

    private static bool Allows(INamedTypeSymbol? type) =>
        type?.GetAttributes().Any(data => data.AttributeClass?.ToDisplayString() == "Microsoft.AspNetCore.Authorization.AllowAnonymousAttribute") == true;

    private static List<string> Access(IEnumerable<(INamedTypeSymbol? Type, bool Live, PageLoader? Loader, string? Head)> segments) =>
        [.. segments.SelectMany(segment => new[] { segment.Loader?.Type, segment.Type })
            .Where(type => type is not null).SelectMany(type => type!.GetAttributes())
            .Where(data => data.AttributeClass?.ToDisplayString() == "Microsoft.AspNetCore.Authorization.AuthorizeAttribute")
            .Select(data =>
            {
                var policy = data.ConstructorArguments.FirstOrDefault().Value as string ?? Named(data, "Policy");
                return $"new global::Aioros.Pages.PageAccess({Optional(policy)}, {Optional(Named(data, "Roles"))})";
            })];

    private static string? Named(AttributeData data, string name) =>
        data.NamedArguments.FirstOrDefault(argument => argument.Key == name).Value.Value as string;

    private static string Optional(string? text) => text is null ? "null" : Literal(text);

    public string BuildData() => DataCodecs.Emit(_codecs);

    public string Build()
    {
        var applicationType = application is null ? "null" : Lazy(application);
        return Header
            + "internal static class AiorosPages\n{\n"
            + $"    public const string ProjectDirectory = {Literal(directory)};\n\n"
            + $"    public static global::System.Func<global::System.Type>? ApplicationType {{ get; }} = {applicationType};\n\n"
            + _views
            + "    public static global::System.Collections.Immutable.ImmutableArray<global::Aioros.Pages.PageDefinition> All { get; } =\n    [\n"
            + _pages
            + "    ];\n\n"
            + "    public static global::Aioros.Pages.PageDefinition? NotFound { get; } = " + _notFound + ";\n\n"
            + "    public static global::Aioros.Pages.PageDefinition? Error { get; } = " + _error + ";\n\n"
            + "    public static global::Aioros.Pages.PageDefinition? NativeOnly { get; } = " + _nativeOnly + ";\n\n"
            + "    private static T Require<T>(" + Provider + " services) where T : class =>\n"
            + "        services.GetService(typeof(T)) as T ?? throw new global::System.InvalidOperationException($\"{typeof(T)} is not registered.\");\n"
            + _factories
            + "}\n";
    }

    private string Factory(INamedTypeSymbol? type, PageLoader? loader)
    {
        if (type is null)
        {
            return "static _ => null";
        }

        if (loader is { Data: not null })
        {
            return $"static _ => throw new global::System.InvalidOperationException(\"{Name(type)} is created from its loader's data.\")";
        }

        var name = $"Model{_factoryCount++}";
        _factories.Append($"\n    private static object? {name}({Provider} services) =>\n        services.GetService(typeof({Name(type)})) ?? {Creation(type, static _ => null)};\n");
        return name;
    }

    private string Loader(string source, INamedTypeSymbol? model, PageLoader loader)
    {
        if (_loaders.TryGetValue(source, out var known))
        {
            return known;
        }

        var index = _loaders.Count;
        var instance = $"services.GetService(typeof({Name(loader.Type)})) as {Name(loader.Type)} ?? {Creation(loader.Type, static _ => null)}";
        if (loader.Call is { } call)
        {
            _factories.Append(Called(index, loader.Type, instance, call));
        }

        if (loader.Data is null)
        {
            var dataless = Dataless(index, model, loader, instance);
            _loaders[source] = dataless;
            return dataless;
        }

        var data = Name(loader.Data);
        var creation = model is null
            ? "null"
            : Creation(model, parameter => SymbolEqualityComparer.Default.Equals(parameter.Type, loader.Data) ? $"({data})data!" : null);
        var members = new List<string>();
        if (loader.Key is { } key)
        {
            _factories.Append($$"""

                    private static global::System.Threading.Tasks.ValueTask<global::Aioros.Pages.LoaderOutcome> Load{{index}}({{Provider}} services, global::Aioros.Pages.PageRequest request, global::System.Threading.CancellationToken cancellationToken) =>
                        throw new global::System.InvalidOperationException("{{loader.Type.ToDisplayString()}} loads every item of a list at once; it runs only for a view repeated in a list.");

                    private static global::System.Threading.Tasks.ValueTask<global::System.Collections.Generic.IReadOnlyList<global::Aioros.Pages.LoaderOutcome>> LoadMany{{index}}({{Provider}} services, global::System.Collections.Generic.IReadOnlyList<object?> inputs, global::Aioros.Pages.PageRequest request, global::System.Threading.CancellationToken cancellationToken) =>
                        global::Aioros.Runtime.Pages.BatchLoads.LoadAsync<{{Name(key)}}, {{data}}>({{instance}}, inputs, request, cancellationToken);

                """);
            members.Add($"LoadManyAsync = LoadMany{index}");
        }
        else if (loader.Call is null)
        {
            _factories.Append($$"""

                    private static async global::System.Threading.Tasks.ValueTask<global::Aioros.Pages.LoaderOutcome> Load{{index}}({{Provider}} services, global::Aioros.Pages.PageRequest request, global::System.Threading.CancellationToken cancellationToken)
                    {
                        var loader = {{instance}};
                        return (await loader.LoadAsync(request, cancellationToken).ConfigureAwait(false)).ToOutcome();
                    }

                """);
        }

        _factories.Append($"\n    private static object? Create{index}({Provider} services, object? data) => {creation};\n");
        var expression = $"new global::Aioros.Pages.LoaderDefinition(Load{index}, Create{index})";
        if (PageLoaders.Receiver(model, loader.Data).Method is { } receive)
        {
            var target = receive.MethodKind == MethodKind.ExplicitInterfaceImplementation ? Name(receive.ExplicitInterfaceImplementations[0].ContainingType) : Name(model!);
            _factories.Append($"\n    private static void Receive{index}(object model, object? data) => (({target})model).Receive(({data})data!);\n");
            members.Add($"Receive = Receive{index}");
        }

        if (shapes.Problem(loader.Data) is null)
        {
            var codec = shapes.Of(loader.Data);
            _codecs.Add(codec);
            members.Add($"Write = {DataCodecs.Class}.Write{codec.Id}, Read = {DataCodecs.Class}.Read{codec.Id}");
        }

        members.AddRange(new[] { Lifetime(loader, string.Empty) }.Where(static lifetime => lifetime.Length > 0));
        if (members.Count > 0)
        {
            expression += " { " + string.Join(", ", members) + " }";
        }

        _loaders[source] = expression;
        return expression;
    }

    private string Dataless(int index, INamedTypeSymbol? model, PageLoader loader, string instance)
    {
        _factories.Append(loader.Call is not null ? string.Empty : $$"""

                private static global::System.Threading.Tasks.ValueTask<global::Aioros.Pages.LoaderOutcome> Load{{index}}({{Provider}} services, global::Aioros.Pages.PageRequest request, global::System.Threading.CancellationToken cancellationToken) =>
                    ({{instance}}).LoadAsync(request, cancellationToken);

            """);
        _factories.Append($$"""

                private static object? Create{{index}}({{Provider}} services, object? data) => {{(model is null ? "null" : $"services.GetService(typeof({Name(model)})) ?? {Creation(model, static _ => null)}")}};

            """);
        return $"new global::Aioros.Pages.LoaderDefinition(Load{index}, Create{index}) {{ Write = static (writer, _) => writer.WriteNullValue(), Read = static _ => null{Lifetime(loader, ", ")} }}";
    }

    /// <summary>
    /// The loader method of a loader found by convention, called directly with its parameters bound from the request; a
    /// route value that does not convert answers not found before the call.
    /// </summary>
    private static string Called(int index, INamedTypeSymbol type, string instance, LoaderCall call)
    {
        var target = call.Method.IsStatic ? Name(type) : "(" + instance + ")";
        var invocation = $"{target}.{call.Method.Name}({string.Join(", ", call.Arguments)})";
        var value = call.Awaited ? $"await {invocation}.ConfigureAwait(false)" : invocation;
        var outcome = call.Shape switch
        {
            LoaderShape.Outcome => value,
            LoaderShape.Result => $"({value}).ToOutcome()",
            _ => $"new global::Aioros.Pages.LoaderOutcome({value})",
        };
        var result = call.Awaited ? outcome : $"new global::System.Threading.Tasks.ValueTask<global::Aioros.Pages.LoaderOutcome>({outcome})";
        var body = string.Concat(call.Statements.Select(statement => "        " + statement + "\n"));
        return $"\n    private static {(call.Awaited ? "async " : string.Empty)}global::System.Threading.Tasks.ValueTask<global::Aioros.Pages.LoaderOutcome> Load{index}({Provider} services, global::Aioros.Pages.PageRequest request, global::System.Threading.CancellationToken cancellationToken)\n    {{\n{body}        return {result};\n    }}\n";
    }

    private static string Lifetime(PageLoader loader, string separator) =>
        loader.Seconds is { } seconds ? separator + "Lifetime = global::System.TimeSpan.FromSeconds(" + seconds.ToString(System.Globalization.CultureInfo.InvariantCulture) + ")" : string.Empty;

    private static string Creation(INamedTypeSymbol type, Func<IParameterSymbol, string?> argument) =>
        PageLoaders.Constructor(type) is { } constructor
            ? $"new {Name(type)}({string.Join(", ", constructor.Parameters.Select(parameter => argument(parameter) ?? $"Require<{Name(parameter.Type)}>(services)"))})"
            : $"Require<{Name(type)}>(services)";

    private static string Name(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    /// <summary>
    /// A function that returns an Avalonia type (the application, a view's class), and none in a build without the
    /// Avalonia engine, so the trimmer keeps none of the type's code.
    /// </summary>
    private string Lazy(ITypeSymbol type) =>
        switched ? $"{Supported} ? static () => typeof({Name(type)}) : null" : $"static () => typeof({Name(type)})";

    private static string Literal(string text) => "@\"" + text.Replace("\"", "\"\"") + "\"";
}
