const BASE = process.argv[2] ?? "http://127.0.0.1:5400";
import { chromium } from "playwright-core";
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox", "--disable-gpu"] });
const page = await browser.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
const requests = [];
page.on("request", r => requests.push(r.url()));
await page.goto(`${BASE}/issues`);
await page.evaluate(() => { window.__marker = 1; });
await page.hover('a[href="/projects"]');
await page.waitForTimeout(400);
const prefetched = requests.filter(u => u.endsWith("/projects")).length;
await page.click('a[href="/projects"]');
await page.waitForFunction(() => location.pathname === "/projects" && document.body.innerText.includes("v2 Launch"));
const kept = await page.evaluate(() => window.__marker === 1);
const fetchedAfter = requests.filter(u => u.endsWith("/projects")).length;
console.log(JSON.stringify({ errors, prefetched, fetchedAfter, sameDocument: kept, fonts: requests.filter(u => u.includes("fonts")) }));
await browser.close();
