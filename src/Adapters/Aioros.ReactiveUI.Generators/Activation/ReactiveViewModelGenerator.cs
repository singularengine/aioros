using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Aioros.ReactiveUI.Generators.Activation;

/// <summary>
/// Finds the app's ReactiveUI view models by their shape at build time (an <c>Activator</c>, a <c>Router</c>, a routable
/// view model) and emits the table the adapter attaches them with, and the <c>AddReactiveRoutes</c> registration that
/// passes it, so no view model is inspected by reflection at run time.
/// </summary>
[Generator]
public sealed class ReactiveViewModelGenerator : IIncrementalGenerator
{
    private const string Adapter = "Aioros.ReactiveUI.Activation.ReactiveViewModels";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var shapes = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is ClassDeclarationSyntax,
            static (syntax, cancellationToken) => syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, cancellationToken) is INamedTypeSymbol type
                ? ViewModelShape.Read(type, syntax.SemanticModel.Compilation)
                : null)
            .Where(static shape => shape is not null)
            .Collect();
        var adapter = context.CompilationProvider.Select(static (compilation, _) =>
            compilation.GetTypeByMetadataName(Adapter) is not null && compilation.GetTypeByMetadataName(ViewModelShape.Routable) is not null);
        context.RegisterSourceOutput(shapes.Combine(adapter), static (output, input) =>
        {
            if (input.Right)
            {
                output.AddSource("AiorosReactiveViewModels.g.cs", Table(input.Left!));
                output.AddSource("AiorosReactiveRoutes.g.cs", Registration);
            }
        });
    }

    private static string Table(ImmutableArray<ViewModelShape?> shapes)
    {
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace Aioros.Generated;\n\n")
            .Append("/// <summary>The app's ReactiveUI view models, found by their shape at build time.</summary>\n")
            .Append("internal static class AiorosReactiveViewModels\n{\n")
            .Append("    public static global::Aioros.ReactiveUI.Activation.ReactiveViewModels All { get; } = new(Attach);\n\n")
            .Append("    private static global::System.IDisposable? Attach(object model, global::Aioros.ReactiveUI.Activation.ReactivePage page)\n    {\n")
            .Append("        switch (model)\n        {\n");
        var index = 0;
        foreach (var shape in shapes.Select(shape => shape!)
            .GroupBy(shape => shape.Name, StringComparer.Ordinal).Select(group => group.First())
            .OrderByDescending(shape => shape.Depth).ThenBy(shape => shape.Name, StringComparer.Ordinal))
        {
            var model = "m" + index++.ToString(System.Globalization.CultureInfo.InvariantCulture);
            code.Append("            case ").Append(shape.Name).Append(' ').Append(model).Append(":\n");
            if (shape.RouterAccess is { } router)
            {
                code.Append("                page.Watch(").Append(Read(model, router, "Router")).Append(");\n");
            }

            if (shape.IsRoutable)
            {
                code.Append("                page.Show(").Append(model).Append(");\n");
            }

            code.Append("                return ").Append(shape.ActivatorAccess is { } activator ? Read(model, activator, "Activator") + "?.Activate()" : "null").Append(";\n");
        }

        return code.Append("            default:\n                return null;\n        }\n    }\n}\n").ToString();
    }

    private static string Read(string model, string access, string member) =>
        access.StartsWith(".", StringComparison.Ordinal) ? model + access : "(" + access + model + ")." + member;

    private const string Registration = """
        // <auto-generated/>
        #nullable enable
        namespace Microsoft.Extensions.DependencyInjection;

        /// <summary>Registers the ReactiveUI adapter with the view models the generator found in this app.</summary>
        internal static class AiorosReactiveRoutesRegistration
        {
            /// <summary>
            /// Registers the ReactiveUI adapter: the page's <c>IScreen</c>, whose navigations go to the route declared here for the
            /// type of the view model navigated to, and the activation of the page's view models, once per page.
            /// </summary>
            public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddReactiveRoutes(
                this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services,
                global::System.Action<global::Aioros.ReactiveUI.Navigation.ReactiveRoutes> routes) =>
                global::Aioros.ReactiveUI.Composition.ReactiveRegistration.AddReactiveRoutes(services, global::Aioros.Generated.AiorosReactiveViewModels.All, routes);
        }

        """;
}
