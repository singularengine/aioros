using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Aioros.Generators.Pages;

internal static class DataCodecs
{
    public const string Class = "global::Aioros.Generated.AiorosLoaderData";

    public const string FunctionClass = "global::Aioros.Generated.AiorosFunctionData";

    private const string Writer = "global::System.Text.Json.Utf8JsonWriter";
    private const string Element = "global::System.Text.Json.JsonElement";
    private const string Null = "global::System.Text.Json.JsonValueKind.Null";

    public static string Hash(string shape)
    {
        var hash = 14695981039346656037UL;
        foreach (var character in shape)
        {
            hash = unchecked((hash ^ character) * 1099511628211UL);
        }

        return hash.ToString("x16", CultureInfo.InvariantCulture);
    }

    public static string Emit(IEnumerable<DataShape> roots) =>
        Emit(roots, "AiorosLoaderData", "Writes and reads each loader's data as JSON for the installed app, without reflection.", objectRoots: true);

    public static string EmitFunctions(IEnumerable<DataShape> roots) =>
        Emit(roots, "AiorosFunctionData", "Writes and reads the arguments and results of the server functions as JSON, without reflection.", objectRoots: false);

    /// <summary>The statement that writes <paramref name="value"/> with the writer <c>w</c>, calling the methods of <paramref name="owner"/>.</summary>
    public static string Write(DataShape shape, string value, string owner) =>
        shape.Kind == ShapeKind.Value ? shape.Write.Replace("{0}", value) : owner + "W" + shape.Id.ToString(CultureInfo.InvariantCulture) + "(w, " + value + ");";

    /// <summary>The expression that reads <paramref name="element"/>, calling the methods of <paramref name="owner"/>.</summary>
    public static string Read(DataShape shape, string element, string owner) =>
        shape.Kind == ShapeKind.Value ? shape.Read.Replace("{0}", element) : owner + "R" + shape.Id.ToString(CultureInfo.InvariantCulture) + "(" + element + ")";

    private static string Emit(IEnumerable<DataShape> roots, string name, string summary, bool objectRoots)
    {
        var code = new StringBuilder("// <auto-generated/>\n#nullable enable\n\nnamespace Aioros.Generated;\n\n");
        code.Append("/// <summary>").Append(summary).Append("</summary>\n");
        code.Append("internal static class ").Append(name).Append("\n{\n");
        code.Append("    private static ").Append(Element).Append(" M(").Append(Element).Append(" e, string name) => e.TryGetProperty(name, out var value) ? value : default;\n");
        var emitted = new HashSet<DataShape>();
        foreach (var root in roots.Distinct().OrderBy(shape => shape.Id))
        {
            if (objectRoots)
            {
                code.Append("\n    public static void Write").Append(root.Id).Append('(').Append(Writer).Append(" w, object? data)\n    {\n        ")
                    .Append(Write(root, "((" + root.Declared + ")data!)", string.Empty)).Append("\n    }\n");
                code.Append("\n    public static object? Read").Append(root.Id).Append('(').Append(Element).Append(" e) => ").Append(Read(root, "e", string.Empty)).Append(";\n");
            }

            Methods(code, root, emitted);
        }

        return code.Append("}\n").ToString();
    }

    private static void Methods(StringBuilder code, DataShape shape, HashSet<DataShape> emitted)
    {
        if (shape.Kind == ShapeKind.Value || !emitted.Add(shape))
        {
            return;
        }

        var reference = !shape.Type.IsValueType;
        var parameter = shape.Declared + (reference ? "?" : string.Empty);
        code.Append("\n    internal static void W").Append(shape.Id).Append('(').Append(Writer).Append(" w, ").Append(parameter).Append(" v)\n    {\n");
        switch (shape.Kind)
        {
            case ShapeKind.Nullable:
                code.Append("        if (v.HasValue)\n        {\n            ").Append(Write(shape.Element!, "v.Value", string.Empty)).Append("\n        }\n        else\n        {\n            w.WriteNullValue();\n        }\n    }\n");
                code.Append("\n    internal static ").Append(shape.Declared).Append(" R").Append(shape.Id).Append('(').Append(Element).Append(" e) => e.ValueKind == ").Append(Null)
                    .Append(" ? null : ").Append(Read(shape.Element!, "e", string.Empty)).Append(";\n");
                break;
            case ShapeKind.Sequence:
                code.Append(reference ? "        if (v is null)\n" : "        if (v.IsDefault)\n").Append("        {\n            w.WriteNullValue();\n            return;\n        }\n\n");
                code.Append("        w.WriteStartArray();\n        foreach (var item in v)\n        {\n            ").Append(Write(shape.Element!, "item", string.Empty)).Append("\n        }\n\n        w.WriteEndArray();\n    }\n");
                code.Append("\n    internal static ").Append(shape.Declared).Append(" R").Append(shape.Id).Append('(').Append(Element).Append(" e)\n    {\n");
                code.Append("        if (e.ValueKind == ").Append(Null).Append(")\n        {\n            return default!;\n        }\n\n");
                code.Append("        var items = new ").Append(ArrayOf(shape)).Append(";\n        var index = 0;\n");
                code.Append("        foreach (var item in e.EnumerateArray())\n        {\n            items[index++] = ").Append(Read(shape.Element!, "item", string.Empty)).Append(";\n        }\n\n");
                code.Append("        return ").Append(shape.Collect).Append(";\n    }\n");
                break;
            case ShapeKind.Map:
                code.Append("        if (v is null)\n        {\n            w.WriteNullValue();\n            return;\n        }\n\n");
                code.Append("        w.WriteStartObject();\n        foreach (var pair in v)\n        {\n            w.WritePropertyName(pair.Key);\n            ").Append(Write(shape.Element!, "pair.Value", string.Empty)).Append("\n        }\n\n        w.WriteEndObject();\n    }\n");
                code.Append("\n    internal static ").Append(shape.Declared).Append(" R").Append(shape.Id).Append('(').Append(Element).Append(" e)\n    {\n");
                code.Append("        if (e.ValueKind == ").Append(Null).Append(")\n        {\n            return null!;\n        }\n\n");
                code.Append("        var map = new global::System.Collections.Generic.Dictionary<string, ").Append(shape.Item).Append(">();\n");
                code.Append("        foreach (var pair in e.EnumerateObject())\n        {\n            map[pair.Name] = ").Append(Read(shape.Element!, "pair.Value", string.Empty)).Append(";\n        }\n\n        return map;\n    }\n");
                break;
            case ShapeKind.Union:
                DataUnions.Emit(code, shape);
                break;
            default:
                Record(code, shape, reference);
                break;
        }

        foreach (var inner in Inner(shape))
        {
            Methods(code, inner, emitted);
        }
    }

    private static void Record(StringBuilder code, DataShape shape, bool reference)
    {
        if (reference)
        {
            code.Append("        if (v is null)\n        {\n            w.WriteNullValue();\n            return;\n        }\n\n");
        }

        code.Append("        w.WriteStartObject();\n        P").Append(shape.Id).Append("(w, v);\n        w.WriteEndObject();\n    }\n");
        code.Append("\n    internal static void P").Append(shape.Id).Append('(').Append(Writer).Append(" w, ").Append(shape.Declared).Append(" v)\n    {\n");
        foreach (var member in shape.Parameters.Concat(shape.Settable))
        {
            code.Append("        w.WritePropertyName(\"").Append(member.Json).Append("\");\n        ").Append(Write(member.Shape, "v." + Escape(member.Name), string.Empty)).Append('\n');
        }

        code.Append("    }\n");
        code.Append("\n    internal static ").Append(shape.Declared).Append(" R").Append(shape.Id).Append('(').Append(Element).Append(" e)\n    {\n");
        if (reference)
        {
            code.Append("        if (e.ValueKind == ").Append(Null).Append(")\n        {\n            return null!;\n        }\n\n");
        }

        code.Append("        return new ").Append(shape.Declared).Append('(')
            .Append(string.Join(", ", shape.Parameters.Select(member => Read(member.Shape, "M(e, \"" + member.Json + "\")", string.Empty))))
            .Append(')');
        if (shape.Settable.Count > 0)
        {
            code.Append(" { ").Append(string.Join(", ", shape.Settable.Select(member => Escape(member.Name) + " = " + Read(member.Shape, "M(e, \"" + member.Json + "\")", string.Empty)))).Append(" }");
        }

        code.Append(";\n    }\n");
    }

    private static IEnumerable<DataShape> Inner(DataShape shape) => shape.Kind switch
    {
        ShapeKind.Record => shape.Parameters.Concat(shape.Settable).Select(member => member.Shape),
        ShapeKind.Union => shape.Derived.Select(derived => derived.Shape).Concat(shape.Fallback ? [shape.Element!] : []),
        _ => shape.Element is null ? [] : [shape.Element],
    };

    private static string ArrayOf(DataShape sequence)
    {
        var type = sequence.Type is IArrayTypeSymbol array ? array.ElementType : ((INamedTypeSymbol)sequence.Type).TypeArguments[0];
        var depth = 0;
        while (type is IArrayTypeSymbol inner)
        {
            (type, depth) = (inner.ElementType, depth + 1);
        }

        return type.ToDisplayString(DataShape.Annotated) + "[e.GetArrayLength()]" + string.Concat(Enumerable.Repeat("[]", depth));
    }

    private static string Escape(string name) =>
        Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name) == Microsoft.CodeAnalysis.CSharp.SyntaxKind.None ? name : "@" + name;
}
